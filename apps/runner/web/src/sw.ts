// VAPP-269: the runner's service worker, written at build time with the
// export's file list: it precaches the shell AND the bundle (`app/`), so the
// app works offline. The cache name hashes every file, so a new export (a new
// package version) is a new cache and the old one goes. No update check, no
// network but the page's own origin.

/** The service worker's source for `files` (scope-relative) under cache `name`. */
export function serviceWorkerSource(name: string, files: readonly string[]): string {
  return `// Generated by apps/runner/web (vite build): the runner's offline cache.
const CACHE = ${JSON.stringify(name)}
const FILES = ${JSON.stringify(files)}
self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES.map((f) => new Request(f, { cache: "reload" })))).then(() => self.skipWaiting()))
})
self.addEventListener("activate", (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("exp-runner-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()))
})
self.addEventListener("fetch", (event) => {
  const request = event.request
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return
  // A navigation (any path, a deep link's query) is the shell.
  const key = request.mode === "navigate" ? new URL("./", self.registration.scope).href : request
  event.respondWith(caches.open(CACHE).then((cache) => cache.match(key, { ignoreSearch: request.mode === "navigate", ignoreVary: true }).then((hit) => hit || fetch(request))))
})
`
}
