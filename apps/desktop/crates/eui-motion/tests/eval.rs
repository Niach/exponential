//! EXP-1603: scores the recorded motion eval (packages/exponential-ui/eval/
//! motion/fixtures/<variant>/<id>.json, recorded by eval/motion/record.ts).
//! A reply is VALID when its JSON parses, compiles (dialect) or validates
//! (Lottie), loads, and paints visible pixels halfway through. Writes
//! eval/motion/report.json; the dialect must reach 95 % first-try validity.
#![cfg(feature = "raster")]

use eui_motion::{dialect, raster, validate, DisplayList, Limits, Motion};
use serde_json::{json, Value};
use std::path::PathBuf;

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../../../packages/exponential-ui/eval/motion")
}

/// The JSON document of a reply: a ```json fence, else the outermost braces.
fn extract(text: &str) -> Option<Value> {
    if let Some(start) = text.find("```json") {
        let rest = &text[start + 7..];
        if let Some(end) = rest.find("```") {
            return serde_json::from_str(rest[..end].trim()).ok();
        }
    }
    let (a, b) = (text.find('{')?, text.rfind('}')?);
    serde_json::from_str(&text[a..=b]).ok()
}

fn score(variant: &str, text: &str) -> Result<(), String> {
    let doc = extract(text).ok_or("no JSON")?;
    let lottie = if variant == "dialect" {
        dialect::compile(&doc).map_err(|e| format!("compile: {}", e.iter().take(3).map(|i| format!("{} {} {}", i.code, i.path, i.message)).collect::<Vec<_>>().join("; ")))?
    } else {
        doc
    };
    let bytes = serde_json::to_vec(&lottie).unwrap();
    let report = validate::check(&bytes, &Limits::default());
    if !report.errors.is_empty() {
        return Err(format!("validate: {}", report.errors.iter().map(|i| i.code.as_str()).collect::<Vec<_>>().join(",")));
    }
    let mut motion = Motion::load(&bytes).map_err(|e| format!("load: {e:?}"))?;
    // Hosts register the theme's fonts for text without glyphs; so does the eval.
    let font = root().join("../../conformance/fonts/Nunito-Regular.ttf");
    motion.add_font("sans", std::fs::read(font).unwrap());
    let (a, b) = motion.frames();
    let mut list = DisplayList::default();
    let mut visible = false;
    for t in [0.5, 0.25, 0.75] {
        motion.sample(a + (b - a) * t, &mut list);
        let pix = raster::paint(&list, 96, 96, &[]);
        if pix.pixels().iter().any(|p| p.alpha() > 8) {
            visible = true;
            break;
        }
    }
    if !visible {
        return Err("draws nothing".into());
    }
    Ok(())
}

#[test]
fn motion_eval() {
    let dir = root().join("fixtures");
    if !dir.exists() {
        eprintln!("no recorded eval fixtures; skipping");
        return;
    }
    let mut rows = Vec::new();
    let mut totals = serde_json::Map::new();
    for variant in ["dialect", "lottie"] {
        let mut files: Vec<_> = std::fs::read_dir(dir.join(variant)).into_iter().flatten().filter_map(|e| e.ok()).map(|e| e.path()).collect();
        files.sort();
        let (mut ok, mut n, mut tokens) = (0, 0, 0u64);
        for f in files {
            let fx: Value = serde_json::from_slice(&std::fs::read(&f).unwrap()).unwrap();
            let text = fx["text"].as_str().unwrap_or("");
            let result = score(variant, text);
            n += 1;
            tokens += fx["usage"]["outputTokens"].as_u64().unwrap_or(0);
            if result.is_ok() {
                ok += 1;
            }
            rows.push(json!({"variant": variant, "id": fx["id"], "valid": result.is_ok(), "error": result.err(), "outputTokens": fx["usage"]["outputTokens"]}));
        }
        if n > 0 {
            totals.insert(variant.into(), json!({"valid": ok, "total": n, "rate": ok as f64 / n as f64, "meanOutputTokens": tokens / n as u64}));
        }
    }
    let report = json!({
        "$comment": "GENERATED by eui-motion tests/eval.rs from fixtures/: first-try validity of the motion dialect vs raw Lottie (EXP-1603).",
        "totals": totals,
        "cases": rows,
    });
    std::fs::write(root().join("report.json"), serde_json::to_string_pretty(&report).unwrap() + "\n").unwrap();
    if let Some(d) = totals.get("dialect") {
        let rate = d["rate"].as_f64().unwrap_or(0.0);
        let failing: Vec<_> = rows.iter().filter(|r| r["variant"] == "dialect" && r["valid"] == false).map(|r| format!("{}: {}", r["id"], r["error"])).collect();
        assert!(rate >= 0.95, "dialect first-try validity {rate:.2} < 0.95:\n{}", failing.join("\n"));
    }
}
