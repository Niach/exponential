\`\`\`

Kotlin: \`at.exponential:engine:$version\` on Maven Central. Licence: see
LICENSE and NOTICE. Generated from the Exponential monorepo
(\`apps/desktop/crates/eengine-ffi\`, tag \`eengine-v$version\`); issues and
changes go there.
MD

echo "wrote $pkg ($([ "$local" = "--local" ] && echo "local path binary" || echo "$url"))"
echo "$zip"
echo "checksum $checksum"
