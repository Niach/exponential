#!/usr/bin/env bash
# #VAPP-263: the SwiftPM distribution of the Engine (`ExponentialEngine`, the
# repo Niach/exponential-engine-swift), Voice's pattern (etalk-ffi/release).
#
#   bash release/swift-package.sh <version> <outdir>           # the release: url + checksum
#   bash release/swift-package.sh <version> <outdir> --local   # a `path:` binary, for `swift build`
#
# Needs out/ExponentialEngineFFI.xcframework first (build-ios.sh). Writes
#   <outdir>/ExponentialEngineFFI.xcframework.zip   (the asset of the eengine-v<version> GitHub release)
#   <outdir>/package/                             (the tree the distribution repo commits and tags <version>)
# and prints `checksum <64 hex>` last. The package: the binary target
# `ExponentialEngineFFI` (`url:` + `checksum:`, SwiftPM refuses file URLs) and
# the target `ExponentialEngine` = the COMMITTED UniFFI binding, product `ExponentialEngine`;
# #VAPP-265: the target + product `ExponentialEngineCapabilities` = swift/ExponentialEngineCapabilities
# (photos, files, share, print, notifications on UIKit/PhotoKit), depending on `ExponentialEngine`.
set -euo pipefail

[ $# -ge 2 ] || { echo "usage: $0 <version> <outdir> [--local]" >&2; exit 2; }
version="$1"; outdir="$2"; local="${3:-}"
[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+([-+].*)?$ ]] || { echo "version must be semver, got $version" >&2; exit 1; }
crate="$(cd "$(dirname "$0")/.." && pwd)"
repo="$(cd "$crate/../../../.." && pwd)"
xcf="$crate/out/ExponentialEngineFFI.xcframework"
[ -d "$xcf" ] || { echo "missing $xcf (run build-ios.sh)" >&2; exit 1; }

mkdir -p "$outdir"
outdir="$(cd "$outdir" && pwd)"
zip="$outdir/ExponentialEngineFFI.xcframework.zip"
pkg="$outdir/package"
rm -rf "$zip" "$pkg"
# --keepParent: ExponentialEngineFFI.xcframework/ at the archive root, the layout SwiftPM expects.
ditto -c -k --sequesterRsrc --keepParent "$xcf" "$zip"

mkdir -p "$pkg/Sources/ExponentialEngine"
cp "$crate/bindings/swift/ExponentialEngineFFI.swift" "$pkg/Sources/ExponentialEngine/"
mkdir -p "$pkg/Sources/ExponentialEngineCapabilities"
cp "$crate"/swift/ExponentialEngineCapabilities/*.swift "$pkg/Sources/ExponentialEngineCapabilities/"
cp "$repo/LICENSE" "$repo/NOTICE" "$pkg/"
checksum="$(cd "$pkg" && swift package compute-checksum "$zip")"
if [ "$local" = "--local" ]; then
  mkdir -p "$pkg/Binaries"
  cp -R "$xcf" "$pkg/Binaries/"
  binary='.binaryTarget(name: "ExponentialEngineFFI", path: "Binaries/ExponentialEngineFFI.xcframework")'
else
  url="https://github.com/Niach/exponential/releases/download/eengine-v$version/ExponentialEngineFFI.xcframework.zip"
  binary=".binaryTarget(name: \"ExponentialEngineFFI\", url: \"$url\", checksum: \"$checksum\")"
fi

cat >"$pkg/Package.swift" <<SWIFT
// swift-tools-version: 5.9
// ExponentialEngine $version: the Engine for Swift (https://exponential.at/sdk/apps/),
// the runtime that runs Apps behind its UniFFI facade. GENERATED by
// apps/desktop/crates/eengine-ffi/release/swift-package.sh; do not edit here.
import PackageDescription

let package = Package(
    name: "ExponentialEngine",
    platforms: [.iOS(.v15), .macOS(.v12)],
    products: [
        .library(name: "ExponentialEngine", targets: ["ExponentialEngine"]),
        // The native capabilities (photos, files, share, print, notifications) for EngineProviders.
        .library(name: "ExponentialEngineCapabilities", targets: ["ExponentialEngineCapabilities"]),
    ],
    targets: [
        // eengine-ffi (iOS device + simulator + macOS, static).
        $binary,
        .target(name: "ExponentialEngine", dependencies: ["ExponentialEngineFFI"]),
        .target(name: "ExponentialEngineCapabilities", dependencies: ["ExponentialEngine"]),
    ]
)
SWIFT

cat >"$pkg/README.md" <<MD
# ExponentialEngine $version

The Engine for Swift: the runtime that runs Apps (instances, lifecycle,
records, the outbox, consent and the capability broker) over your app's
providers (Keychain vault, windows, native capabilities) on iOS 15+ and
macOS 12+. Painting stays in the app (genUI's \`ExponentialUI\`). Docs:
**https://exponential.at/sdk/apps/**; the API:
\`apps/desktop/crates/eengine-ffi/README.md\` in the monorepo.

\`\`\`swift
// Package.swift
.package(url: "https://github.com/Niach/exponential-engine-swift", exact: "$version")
// target
.product(name: "ExponentialEngine", package: "exponential-engine-swift")
\`\`\`

\`\`\`swift
