//! `.exp-pi-mcp.ts` for spawned `pi` sessions (EXP-201) — pi has **no native
//! MCP support**, so the launcher writes this TypeScript extension into the
//! worktree and passes it via `-e`/`--extension`. The extension bridges the
//! Exponential MCP server into pi's own tool registry: it speaks MCP
//! streamable-HTTP JSON-RPC (initialize → tools/list → per-call tools/call)
//! against `EXP_MCP_URL` and registers every `exponential_*` tool under its
//! ORIGINAL name, so the seed prompts' tool contract
//! (`exponential_comments_list` → implement → `exponential_pr_open`) needs no
//! pi-specific variant.
//!
//! Unlike `.exp-mcp.json`, this file carries **no secret**: the server URL and
//! the raw `expu_` key ride the spawn env (`EXP_MCP_URL` / `EXP_MCP_TOKEN`),
//! so the bridge is a static byte-stable artifact. It still lands in the
//! worktree (pi resolves `-e` paths relative to cwd) and is kept out of
//! `git add -A` via the same repo-local excludes as the MCP config.
//!
//! Loading via `-e` is deliberate: it works independent of pi's project-trust
//! prompt (which gates `.pi/extensions/` auto-discovery), and the launcher
//! never passes `-a`/`--approve` — that would auto-trust repo-carried
//! extensions in a permission-free session. The file has ZERO imports: pi
//! loads extensions through jiti (plain TypeScript is fine), but `typebox`
//! may not resolve from an arbitrary worktree — and MCP `inputSchema` values
//! are plain JSON Schema objects, which is exactly what TypeBox schemas are
//! at runtime, so they pass through verbatim.

use std::io;
use std::path::{Path, PathBuf};

use crate::mcp_json::write_private;

pub const PI_BRIDGE_FILE: &str = ".exp-pi-mcp.ts";

/// The bridge source — static and byte-stable (no interpolation; the env
/// carries the per-session values).
pub const PI_BRIDGE_SOURCE: &str = r#"// AUTO-GENERATED by the Exponential desktop launcher — do not edit or commit.
// Bridges pi (no native MCP support) to the Exponential MCP server: registers
// every exponential_* tool by speaking MCP streamable-HTTP JSON-RPC against
// EXP_MCP_URL with the bearer token from EXP_MCP_TOKEN. No secrets in this
// file; both values ride the spawn environment.
export default async function (pi: any) {
  const url = process.env.EXP_MCP_URL
  const token = process.env.EXP_MCP_TOKEN
  if (!url || !token) return
  let sessionId: string | undefined
  let nextId = 1
  const rpc = async (method: string, params?: unknown): Promise<any> => {
    const headers: Record<string, string> = {
      "content-type": "application/json",
      accept: "application/json, text/event-stream",
      authorization: `Bearer ${token}`,
    }
    if (sessionId) headers["mcp-session-id"] = sessionId
    // EXP-637: the run's coding_sessions row, so exponential_sessions_end
    // (and the self-merge spare) resolve the caller. Not a secret.
    const runSession = process.env.EXP_MCP_SESSION_ID
    if (runSession) headers["x-exp-session-id"] = runSession
    const body: Record<string, unknown> = { jsonrpc: "2.0", method }
    if (params !== undefined) body.params = params
    const notification = method.startsWith("notifications/")
    if (!notification) body.id = nextId++
    const res = await fetch(url, { method: "POST", headers, body: JSON.stringify(body) })
    sessionId = res.headers.get("mcp-session-id") ?? sessionId
    if (notification) return undefined
    if (!res.ok) throw new Error(`MCP ${method} failed: HTTP ${res.status}`)
    const contentType = res.headers.get("content-type") ?? ""
    let payload: any
    if (contentType.includes("text/event-stream")) {
      // Streamable HTTP may answer a POST as a one-shot SSE stream — the
      // response is the last data: event carrying JSON.
      for (const line of (await res.text()).split("\n")) {
        const trimmed = line.trim()
        if (trimmed.startsWith("data:")) {
          try {
            payload = JSON.parse(trimmed.slice(5).trim())
          } catch {}
        }
      }
    } else {
      payload = await res.json()
    }
    if (!payload) throw new Error(`MCP ${method} returned no response`)
    if (payload.error) throw new Error(payload.error.message ?? `MCP ${method} error`)
    return payload.result
  }

  await rpc("initialize", {
    protocolVersion: "2025-03-26",
    capabilities: {},
    clientInfo: { name: "exponential-pi-bridge", version: "1.0.0" },
  })
  await rpc("notifications/initialized")
  const listed = await rpc("tools/list")
  const tools = listed?.tools ?? []
  for (const tool of tools) {
    pi.registerTool({
      name: tool.name,
      label: tool.name,
      description: tool.description ?? tool.name,
      // MCP inputSchema is plain JSON Schema — the same shape TypeBox
      // schemas have at runtime, so it passes through verbatim.
      parameters: tool.inputSchema ?? { type: "object", properties: {} },
      async execute(_toolCallId: string, params: any) {
        const result = await rpc("tools/call", { name: tool.name, arguments: params ?? {} })
        const text = (result?.content ?? [])
          .filter((block: any) => block?.type === "text")
          .map((block: any) => block.text)
          .join("\n")
        if (result?.isError) throw new Error(text || `${tool.name} failed`)
        return { content: [{ type: "text", text }], details: {} }
      },
    })
  }

  // EXP-637 — tool search. The whole exponential_* surface is far more
  // context than a run needs up front, so only the CORE set (the server's
  // per-tool `_meta["anthropic/alwaysLoad"]`, the same flag Claude Code and
  // codex honor natively) stays active; everything else is discovered on
  // demand through exponential_search_tools. Every call is wrapped: a pi
  // build without get/setActiveTools degrades OPEN — all tools active, which
  // is exactly the pre-EXP-637 behavior.
  const core = tools
    .filter((tool: any) => tool?._meta?.["anthropic/alwaysLoad"] === true)
    .map((tool: any) => tool.name)
  const SEARCH_TOOL = "exponential_search_tools"
  pi.registerTool({
    name: SEARCH_TOOL,
    label: SEARCH_TOOL,
    description:
      "Search the Exponential MCP tools by keyword and ACTIVATE the matches for this " +
      "session. Use it before any operation the currently loaded exponential_* tools " +
      "do not cover (boards, labels, members, attachments, notifications, actions, " +
      "automations, repositories, invites, teams).",
    parameters: {
      type: "object",
      properties: { query: { type: "string", description: "Keywords, e.g. \"labels\"." } },
      required: ["query"],
    },
    async execute(_toolCallId: string, params: any) {
      const terms = String(params?.query ?? "")
        .toLowerCase()
        .split(/\s+/)
        .filter(Boolean)
      const matches = tools.filter((tool: any) => {
        const haystack = `${tool.name} ${tool.description ?? ""}`.toLowerCase()
        return terms.length === 0 || terms.some((term: string) => haystack.includes(term))
      })
      try {
        const active = pi.getActiveTools?.() ?? []
        pi.setActiveTools?.([...new Set([...active, ...matches.map((t: any) => t.name)])])
      } catch {}
      const text = matches.length
        ? matches.map((t: any) => `${t.name} — ${t.description ?? ""}`.trim()).join("\n")
        : "No matching Exponential tools."
      return { content: [{ type: "text", text }], details: {} }
    },
  })
  const activateCore = () => {
    try {
      const active = pi.getActiveTools?.()
      if (!active || !pi.setActiveTools) return
      const foreign = active.filter((name: string) => !name.startsWith("exponential_"))
      pi.setActiveTools([...new Set([...foreign, ...core, SEARCH_TOOL])])
    } catch {}
  }
  try {
    pi.on?.("session_start", activateCore)
  } catch {}
  activateCore()
}
"#;

/// Write the bridge into the worktree root. Overwrites every launch so a
/// newer app version's bridge always wins over a stale copy in a reused
/// worktree. Same private-write posture as `.exp-mcp.json` (no secret here,
/// but no reason to be looser).
pub fn write_pi_bridge(worktree: &Path) -> io::Result<PathBuf> {
    let path = worktree.join(PI_BRIDGE_FILE);
    write_private(&path, PI_BRIDGE_SOURCE)?;
    Ok(path)
}

pub const PI_OBSERVER_FILE: &str = ".exp-pi-observer.ts";

/// The observer extension (EXP-383) — the pi analogue of the claude hooks
/// sidecar. Subscribes to pi's extension events and POSTs batched activity
/// to the desktop's loopback observer server (`steer::pi_observer`), and
/// long-polls it for remote steer messages applied via `pi.sendUserMessage`
/// (pi's own queue semantics — while streaming, `deliverAs` is REQUIRED and
/// `"steer"` delivers at the next tool boundary; when idle it must be
/// OMITTED so the message triggers a turn).
///
/// EXP-724: the same long-poll carries remote SLASH COMMANDS, which must
/// never go through `sendUserMessage` — pi dispatches its built-ins only in
/// the TUI's `onSubmit`, so `/compact` sent as a message is just text for
/// the model. `compact` runs `ctx.compact()`, `new` runs `ctx.newSession()`
/// and `model` resolves through `ctx.modelRegistry` into `pi.setModel`; the
/// live `ctx` is rebound on every `session_start` so a `/new` leaves the
/// pump steering the session that replaced it. The compaction edges pi
/// raises (`session_before_compact`/`session_compact`) are reported too —
/// they are the only agent's compaction with a real START marker.
///
/// Same contract as the MCP bridge: static byte-stable file, zero imports,
/// no secrets (url + token ride `EXP_OBSERVER_URL`/`EXP_OBSERVER_TOKEN` in
/// the spawn env — the file is inert without them). Extension rules per pi
/// v0.83 docs: never write to stdout (the TUI owns it), start background
/// work in `session_start` (never the factory — `--list-models` runs
/// factories without a session), stop it in `session_shutdown`, and swallow
/// every failure — a dead sidecar must never wedge the coding session.
/// Unknown `pi.on` event names are no-ops on older pi versions.
pub const PI_OBSERVER_SOURCE: &str = r#"// AUTO-GENERATED by the Exponential desktop launcher — do not edit or commit.
// Reports pi session activity to the desktop's loopback observer sidecar and
// applies remote steer messages via pi.sendUserMessage. No secrets in this
// file; EXP_OBSERVER_URL / EXP_OBSERVER_TOKEN ride the spawn environment.
export default function (pi: any) {
  const url = process.env.EXP_OBSERVER_URL
  const token = process.env.EXP_OBSERVER_TOKEN
  if (!url || !token) return
  const cwd = process.cwd()

  let stopped = false
  let queue: any[] = []
  let flushTimer: any = null

  const post = async (path: string, body: unknown): Promise<any> => {
    const res = await fetch(`${url}${path}`, {
      method: "POST",
      headers: { "content-type": "application/json", authorization: `Bearer ${token}` },
      body: JSON.stringify(body),
    })
    if (!res.ok) throw new Error(`observer ${path}: HTTP ${res.status}`)
    return res.status === 204 ? undefined : await res.json()
  }

  const flush = () => {
    if (flushTimer) { clearTimeout(flushTimer); flushTimer = null }
    if (!queue.length) return
    const events = queue
    queue = []
    post("/events", { cwd, events }).catch(() => {})
  }
  // Coalesce: one POST per burst, never one per event.
  const emit = (event: Record<string, unknown>) => {
    if (stopped) return
    queue.push(event)
    if (queue.length >= 20) return void flush()
    if (!flushTimer) flushTimer = setTimeout(flush, 300)
  }

  const on = (name: string, handler: (e: any, ctx: any) => void) => {
    // Unknown events are a no-op on older pi; a throwing handler must never
    // reach pi's error surface.
    pi.on(name, (e: any, ctx: any) => {
      try { handler(e, ctx) } catch {}
    })
  }

  // The live session context. Rebound on every session_start, so a /new
  // (ctx.newSession) leaves the pump steering the CURRENT session.
  let liveCtx: any = null

  // --- commands (inbound) --------------------------------------------------
  // Built-in slash commands dispatch only in pi's TUI onSubmit, so
  // sendUserMessage("/compact") would just send the literal text to the
  // model. These run pi's own APIs instead.
  const failCommand = (name: string, err: any) => {
    emit({ kind: "command_failed", name, message: String(err?.message ?? err) })
    flush()
  }
  const resolveModel = (spec: string): any => {
    const registry = liveCtx?.modelRegistry
    if (!registry || !spec) return undefined
    const slash = spec.indexOf("/")
    if (slash > 0) {
      const found = registry.find?.(spec.slice(0, slash), spec.slice(slash + 1))
      if (found) return found
    }
    // Bare id: prefer the models this machine actually has auth for —
    // getAll() also lists providers with no API key, and setModel() then
    // returns false on a name that looked like a perfect match.
    const lowered = spec.toLowerCase()
    for (const pool of [registry.getAvailable?.() ?? [], registry.getAll?.() ?? []]) {
      const hit = pool.find((model: any) => model?.id === spec)
        ?? pool.find((model: any) => String(model?.id ?? "").toLowerCase() === lowered)
      if (hit) return hit
    }
    return undefined
  }
  const runCommand = async (name: string, args: string) => {
    try {
      const ctx = liveCtx
      if (name === "compact") {
        if (typeof ctx?.compact !== "function") throw new Error("this pi build has no compact API")
        ctx.compact({
          customInstructions: args || undefined,
          onError: (err: any) => failCommand(name, err),
        })
      } else if (name === "new") {
        if (typeof ctx?.newSession !== "function") throw new Error("this pi build cannot start a new session")
        await ctx.newSession()
      } else if (name === "model") {
        const model = resolveModel(args)
        if (!model) throw new Error(`no model matches ${args}`)
        // false = no API key configured for that model (pi docs).
        if ((await pi.setModel(model)) === false) throw new Error(`no API key for ${args}`)
      } else {
        return
      }
      emit({ kind: "command", name, args })
      flush()
    } catch (err) {
      failCommand(name, err)
    }
  }

  // --- steering (inbound) --------------------------------------------------
  // Long-poll the sidecar; apply each remote composer message through pi's
  // own queue and each remote slash command through pi's own API. Started
  // from session_start (never the factory), stopped by session_shutdown.
  let pumping = false
  const startSteerPump = (bootCtx: any) => {
    if (pumping) return
    pumping = true
    const pump = async () => {
      while (!stopped) {
        try {
          const next = await post("/steer", { cwd })
          const ctx = liveCtx ?? bootCtx
          for (const text of next?.messages ?? []) {
            if (typeof text !== "string" || !text.length) continue
            try {
              // deliverAs is REQUIRED while streaming and must be OMITTED
              // when idle (it would throw / not start a turn otherwise).
              if (ctx.isIdle()) pi.sendUserMessage(text)
              else pi.sendUserMessage(text, { deliverAs: "steer" })
            } catch {}
          }
          for (const command of next?.commands ?? []) {
            if (typeof command?.name !== "string") continue
            await runCommand(command.name, typeof command.args === "string" ? command.args : "")
          }
        } catch {
          await new Promise((resolve) => setTimeout(resolve, 2000))
        }
      }
    }
    void pump()
  }

  // --- observation ---------------------------------------------------------
  on("session_start", (_e, ctx) => {
    liveCtx = ctx
    emit({ kind: "session_start" })
    startSteerPump(ctx)
  })
  on("input", (e) => {
    // interactive = typed in the TUI; extension = our own injected steer
    // (forwarded so OTHER viewers see it — the sender's client dedupes).
    if (e?.source !== "interactive" && e?.source !== "extension") return
    if (typeof e?.text !== "string" || !e.text.length) return
    emit({ kind: "input", text: e.text, source: e.source })
  })
  on("agent_start", () => emit({ kind: "agent_start" }))
  // agent_settled is the true idle signal: pi may still auto-retry,
  // auto-compact, or continue with queued follow-ups after agent_end. It is
  // also a recent addition (absent before ~0.8x), so agent_end doubles as
  // the fallback — on newer pi both fire and the flag write is idempotent;
  // a premature idle from agent_end is corrected by the next agent_start.
  on("agent_settled", () => { emit({ kind: "agent_settled" }); flush() })
  on("agent_end", () => { emit({ kind: "agent_settled" }); flush() })
  on("message_update", (e) => {
    const ev = e?.assistantMessageEvent
    if (ev?.type === "text_end" && typeof ev.content === "string" && ev.content.length) {
      emit({ kind: "text", text: ev.content })
    } else if (ev?.type === "thinking_end" && typeof ev.content === "string" && ev.content.length) {
      emit({ kind: "thinking", text: ev.content })
    }
  })
  on("tool_execution_start", (e) => {
    if (typeof e?.toolName !== "string") return
    emit({ kind: "tool_start", id: e.toolCallId ?? "", name: e.toolName, args: e.args ?? {} })
  })
  on("tool_execution_end", (e) => {
    if (typeof e?.toolName !== "string") return
    emit({ kind: "tool_end", id: e.toolCallId ?? "", isError: e.isError === true })
  })
  // Compaction: pi's reason vocabulary is manual | threshold | overflow; the
  // steer wire carries manual | auto only.
  on("session_before_compact", (e) => {
    emit({ kind: "compaction", phase: "started", trigger: e?.reason === "manual" ? "manual" : "auto" })
    flush()
  })
  on("session_compact", () => { emit({ kind: "compaction", phase: "ended" }); flush() })
  on("session_shutdown", () => {
    emit({ kind: "session_shutdown" })
    flush()
    stopped = true
  })
}
"#;

