pub const PI_PLAN_FILE: &str = ".exp-pi-plan.ts";

/// Plan mode for pi (EXP-441) — pi has no native plan mode, so this
/// launcher-written extension implements one: a plan-first system-prompt
/// section, a mutating-tool gate (`write`/`edit` plus mutating
/// `exponential_*` MCP tools; bash stays available under read-only prompt
/// discipline), and an `exit_plan_mode` tool whose approval runs through
/// pi's native `ctx.ui.confirm` dialog. The plan lifecycle posts
/// `plan_pending`/`plan_resolved` events to the observer sidecar so remote
/// viewers get the standard plan-approval card and the emitter can resolve
/// the dialog by pty keystroke on a remote answer (`steer::pi_activity`).
///
/// Same contract as the other two extensions: static byte-stable file, zero
/// imports, no stdout, no secrets (`EXP_PI_PLAN_MODE=1` gates it on;
/// `EXP_OBSERVER_URL`/`EXP_OBSERVER_TOKEN` ride the spawn env), and every
/// failure swallowed — a dead sidecar or an older pi API surface must never
/// wedge the coding session. A pi without `ctx.ui.confirm` degrades OPEN
/// (auto-approve): a gate nobody can ever approve would wedge the session
/// outright, which is worse than losing the gate.
pub const PI_PLAN_SOURCE: &str = r###"// AUTO-GENERATED by the Exponential desktop launcher — do not edit or commit.
// Plan mode for pi: blocks mutating tools until the user approves a plan
// presented via the exit_plan_mode tool and pi's native confirm dialog.
// Inert without EXP_PI_PLAN_MODE=1. No secrets in this file;
// EXP_OBSERVER_URL / EXP_OBSERVER_TOKEN ride the spawn environment.
export default function (pi: any) {
  if (process.env.EXP_PI_PLAN_MODE !== "1") return
  const url = process.env.EXP_OBSERVER_URL
  const token = process.env.EXP_OBSERVER_TOKEN
  const cwd = process.cwd()

  let planning = true

  // One-shot POST to the observer sidecar's /events route (same wire shape
  // the observer extension batches). Never batched: a pending plan must
  // reach remote viewers immediately. Failures are swallowed — without a
  // sidecar the local confirm dialog still works.
  const post = (event: Record<string, unknown>): Promise<void> => {
    if (!url || !token) return Promise.resolve()
    return fetch(`${url}/events`, {
      method: "POST",
      headers: { "content-type": "application/json", authorization: `Bearer ${token}` },
      body: JSON.stringify({ cwd, events: [event] }),
    }).then(() => undefined, () => undefined)
  }

  const setStatus = (ctx: any, text: string | undefined) => {
    try { ctx?.ui?.setStatus?.("exp-plan", text) } catch {}
  }

  // Read-only exponential_* MCP tools stay callable during planning; every
  // other exponential_* tool mutates (create/update/delete/pr_open/...).
  const readOnlySuffixes = ["_list", "_get", "_pr_files", "_branch_diff"]
  const blockedWhilePlanning = (name: string): boolean => {
    if (name === "write" || name === "edit") return true
    // EXP-637: tool SEARCH is read-only discovery — planning needs it to
    // reach the deferred exponential_* surface at all.
    if (name === "exponential_search_tools") return false
    if (name.startsWith("exponential_")) {
      return !readOnlySuffixes.some((suffix) => name.endsWith(suffix))
    }
    return false
  }

  const planPrompt = [
    "",
    "## Plan mode (active)",
    "The user wants to review an implementation plan before you change anything.",
    "- Do NOT modify anything yet. The write and edit tools are blocked, and bash",
    "  must be used strictly read-only: no file writes or deletes, no git",
    "  commit/push, no package installs, no state-changing commands.",
    "- Investigate the repository first, then call the exit_plan_mode tool with",
    "  your full implementation plan as markdown.",
    "- The user approves or rejects the plan. Only after approval may you start",
    "  making changes. If rejected, wait for feedback, revise, and call",
    "  exit_plan_mode again.",
  ].join("\n")

  try {
    pi.registerTool({
      name: "exit_plan_mode",
      label: "Exit plan mode",
      description:
        "Present your implementation plan to the user for approval. Call this once your investigation is complete, passing the full plan as markdown. Implementation may only begin after this tool returns approval.",
      parameters: {
        type: "object",
        properties: {
          plan: { type: "string", description: "The full implementation plan, as markdown." },
        },
        required: ["plan"],
      },
      async execute(_toolCallId: string, _params: any) {
        // Approval already ran in the tool_call interceptor below — a
        // rejected plan never reaches execute (the call is blocked there).
        return {
          content: [{ type: "text", text: "Plan approved — proceed with the implementation." }],
          details: {},
        }
      },
    })
  } catch {}

  try {
    pi.on("before_agent_start", (event: any) => {
      try {
        if (!planning) return undefined
        return { systemPrompt: `${event?.systemPrompt ?? ""}${planPrompt}` }
      } catch {
        return undefined
      }
    })
  } catch {}

  try {
    pi.on("session_start", (_event: any, ctx: any) => {
      try {
        if (planning) setStatus(ctx, "plan mode")
      } catch {}
    })
  } catch {}

  try {
    pi.on("tool_call", async (event: any, ctx: any) => {
      try {
        const name = event?.toolName
        if (typeof name !== "string") return undefined
        if (name === "exit_plan_mode") {
          if (!planning) return undefined
          const input = event?.input ?? {}
          const plan = typeof input.plan === "string" ? input.plan : ""
          const id =
            typeof event?.toolCallId === "string" && event.toolCallId.length
              ? event.toolCallId
              : `plan-${Date.now()}`
          await post({ kind: "plan_pending", id, plan })
          setStatus(ctx, "plan awaiting approval")
          let approved = false
          const confirm = ctx?.ui?.confirm
          if (typeof confirm !== "function") {
            // Older pi without a confirm surface: degrade OPEN — an
            // unapprovable plan gate would wedge the session outright.
            approved = true
          } else {
            try {
              approved = (await confirm.call(ctx.ui, "Approve plan?", plan)) === true
            } catch {
              approved = false
            }
          }
          await post({ kind: "plan_resolved", id, approved })
          if (approved) {
            planning = false
            setStatus(ctx, undefined)
            return undefined // allow the tool — execute() returns the approval text
          }
          setStatus(ctx, "plan mode")
          // terminate stops the agent after this blocked batch (verified
          // against pi 0.84.1: early termination fires when every blocked
          // call in the batch sets it — this is a single call), handing
          // control back to the user for feedback.
          return {
            block: true,
            reason:
              "The user rejected the plan. Stay in plan mode: wait for their feedback, then revise the plan and call exit_plan_mode again.",
            terminate: true,
          }
        }
        if (planning && blockedWhilePlanning(name)) {
          return {
            block: true,
            reason: `Plan mode is active: ${name} is not allowed yet. Investigate read-only and present your plan via the exit_plan_mode tool first.`,
          }
        }
        return undefined
      } catch {
        return undefined
      }
    })
  } catch {}
}
"###;

