    fn bridge_is_static_env_configured_and_importless() {
        // No per-session interpolation — the env carries url + token, so the
        // file itself must never contain a secret placeholder.
        assert!(!PI_BRIDGE_SOURCE.contains("expu_"));
        assert!(PI_BRIDGE_SOURCE.contains("EXP_MCP_URL"));
        assert!(PI_BRIDGE_SOURCE.contains("EXP_MCP_TOKEN"));
        // Zero imports: typebox/pi packages may not resolve from an arbitrary
        // worktree; the extension must be self-contained.
        assert!(!PI_BRIDGE_SOURCE.contains("import "));
        // The pi extension contract: default async factory + registerTool.
        assert!(PI_BRIDGE_SOURCE.contains("export default async function (pi: any)"));
        assert!(PI_BRIDGE_SOURCE.contains("pi.registerTool"));
        // The MCP handshake + tool pass-through (original tool names).
        for needle in ["initialize", "notifications/initialized", "tools/list", "tools/call"] {
            assert!(PI_BRIDGE_SOURCE.contains(needle), "missing {needle}");
        }
    }

    /// EXP-637: the bridge defers the full exponential_* surface behind a
    /// search tool (pi's documented dynamic tool loading) and identifies the
    /// run to the server. Still zero-import, still secret-free.
    #[test]
    fn bridge_defers_tools_behind_search_and_sends_the_session_header() {
        assert!(PI_BRIDGE_SOURCE.contains("exponential_search_tools"));
        assert!(PI_BRIDGE_SOURCE.contains(r#"anthropic/alwaysLoad"#));
        assert!(PI_BRIDGE_SOURCE.contains("setActiveTools"));
        assert!(PI_BRIDGE_SOURCE.contains("getActiveTools"));
        assert!(PI_BRIDGE_SOURCE.contains(r#"pi.on?.("session_start""#));
        // The session header (env-carried, never interpolated into the file).
        assert!(PI_BRIDGE_SOURCE.contains("EXP_MCP_SESSION_ID"));
        assert!(PI_BRIDGE_SOURCE.contains("x-exp-session-id"));
        // The file stays byte-stable, import-free and secret-free.
        assert!(!PI_BRIDGE_SOURCE.contains("import "));
        assert!(!PI_BRIDGE_SOURCE.contains("console."));
        assert!(!PI_BRIDGE_SOURCE.contains("expu_"));
        // Degrading OPEN matters more than deferring: every registry call is
        // wrapped, so a pi without the API keeps all tools active.
        assert!(PI_BRIDGE_SOURCE.contains("} catch {}"));
    }

    #[test]
    fn observer_is_static_env_configured_importless_and_stdout_free() {
        // Same contract as the MCP bridge: env-configured, zero imports.
        assert!(!PI_OBSERVER_SOURCE.contains("expu_"));
        assert!(PI_OBSERVER_SOURCE.contains("EXP_OBSERVER_URL"));
        assert!(PI_OBSERVER_SOURCE.contains("EXP_OBSERVER_TOKEN"));
        assert!(!PI_OBSERVER_SOURCE.contains("import "));
        // pi's TUI owns stdout — an extension must never write to it.
        assert!(!PI_OBSERVER_SOURCE.contains("console."));
        assert!(PI_OBSERVER_SOURCE.contains("export default function (pi: any)"));
        // The full observation set (unknown names no-op on older pi).
        for event in [
            "session_start",
            "input",
            "agent_start",
            "agent_settled",
            "agent_end", // idle fallback for pi builds predating agent_settled
            "message_update",
            "tool_execution_start",
            "tool_execution_end",
            // EXP-724: pi is the one agent with a real compaction START.
            "session_before_compact",
            "session_compact",
            "session_shutdown",
        ] {
            assert!(
                PI_OBSERVER_SOURCE.contains(&format!("on(\"{event}\"")),
                "missing subscription: {event}"
            );
        }
        // EXP-724: commands run pi's own APIs — never sendUserMessage, which
        // would hand `/compact` to the model as literal text.
        assert!(PI_OBSERVER_SOURCE.contains("ctx.compact({"));
        assert!(PI_OBSERVER_SOURCE.contains("ctx.newSession()"));
        assert!(PI_OBSERVER_SOURCE.contains("pi.setModel(model)"));
        assert!(PI_OBSERVER_SOURCE.contains("next?.commands ?? []"));
        // The steer contract: deliverAs required while streaming, omitted
        // when idle; background work starts in session_start, never the
        // factory (pi runs factories for --list-models etc.).
        assert!(PI_OBSERVER_SOURCE.contains("ctx.isIdle()"));
        assert!(PI_OBSERVER_SOURCE.contains(r#"{ deliverAs: "steer" }"#));
        assert!(PI_OBSERVER_SOURCE.contains("startSteerPump(ctx)"));
        // The sidecar routes: batched events + the steer long-poll.
        assert!(PI_OBSERVER_SOURCE.contains(r#""/events""#));
        assert!(PI_OBSERVER_SOURCE.contains(r#""/steer""#));
    }

