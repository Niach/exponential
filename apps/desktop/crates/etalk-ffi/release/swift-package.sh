#!/usr/bin/env bash
# #EXP-1441: the SwiftPM distribution of eTalk (`ExponentialTalk`, the repo
# Niach/exponential-talk-swift), eUI's pattern (packages/exponential-ui-swift/release).
#
#   bash release/swift-package.sh <version> <outdir>           # the release: url + checksum
#   bash release/swift-package.sh <version> <outdir> --local   # a `path:` binary, for `swift build`
#
# Needs out/ExponentialTalkFFI.xcframework first (build-ios.sh). Writes
#   <outdir>/ExponentialTalkFFI.xcframework.zip   (the asset of the etalk-v<version> GitHub release)
#   <outdir>/package/                             (the tree the distribution repo commits and tags <version>)
# and prints `checksum <64 hex>` last. The package: the binary target
# `ExponentialTalkFFI` (`url:` + `checksum:`, SwiftPM refuses file URLs) and
# the target `ExponentialTalk` = the COMMITTED UniFFI binding, product `ExponentialTalk`.
set -euo pipefail

[ $# -ge 2 ] || { echo "usage: $0 <version> <outdir> [--local]" >&2; exit 2; }
version="$1"; outdir="$2"; local="${3:-}"
[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+([-+].*)?$ ]] || { echo "version must be semver, got $version" >&2; exit 1; }
crate="$(cd "$(dirname "$0")/.." && pwd)"
repo="$(cd "$crate/../../../.." && pwd)"
xcf="$crate/out/ExponentialTalkFFI.xcframework"
[ -d "$xcf" ] || { echo "missing $xcf (run build-ios.sh)" >&2; exit 1; }

mkdir -p "$outdir"
outdir="$(cd "$outdir" && pwd)"
zip="$outdir/ExponentialTalkFFI.xcframework.zip"
pkg="$outdir/package"
rm -rf "$zip" "$pkg"
# --keepParent: ExponentialTalkFFI.xcframework/ at the archive root, the layout SwiftPM expects.
ditto -c -k --sequesterRsrc --keepParent "$xcf" "$zip"

mkdir -p "$pkg/Sources/ExponentialTalk"
cp "$crate/bindings/swift/ExponentialTalkFFI.swift" "$pkg/Sources/ExponentialTalk/"
cp "$repo/LICENSE" "$repo/NOTICE" "$pkg/"
checksum="$(cd "$pkg" && swift package compute-checksum "$zip")"
if [ "$local" = "--local" ]; then
  mkdir -p "$pkg/Binaries"
  cp -R "$xcf" "$pkg/Binaries/"
  binary='.binaryTarget(name: "ExponentialTalkFFI", path: "Binaries/ExponentialTalkFFI.xcframework")'
else
  url="https://github.com/Niach/exponential/releases/download/etalk-v$version/ExponentialTalkFFI.xcframework.zip"
  binary=".binaryTarget(name: \"ExponentialTalkFFI\", url: \"$url\", checksum: \"$checksum\")"
fi

cat >"$pkg/Package.swift" <<SWIFT
// swift-tools-version: 5.9
// ExponentialTalk $version: eTalk for Swift (https://exponential.at/talk/), the
// call machine and the Opus codec behind their UniFFI facade. GENERATED by
// apps/desktop/crates/etalk-ffi/release/swift-package.sh; do not edit here.
import PackageDescription

let package = Package(
    name: "ExponentialTalk",
    platforms: [.iOS(.v15), .macOS(.v12)],
    products: [
        .library(name: "ExponentialTalk", targets: ["ExponentialTalk"]),
    ],
    targets: [
        // etalk-ffi (iOS device + simulator + macOS, static).
        $binary,
        .target(name: "ExponentialTalk", dependencies: ["ExponentialTalkFFI"]),
    ]
)
SWIFT

cat >"$pkg/README.md" <<MD
# ExponentialTalk $version

eTalk for Swift: the call machine (the ring, the warm-up, the agent speaks
first; fixture-locked by \`voice-call.json\`) and the Opus codec (PCM in,
packets out) on iOS 15+ and macOS 12+. Audio I/O and transport stay in the
app. Docs: **https://exponential.at/talk/**; the API:
\`apps/desktop/crates/etalk-ffi/README.md\` in the monorepo.

\`\`\`swift
// Package.swift
.package(url: "https://github.com/Niach/exponential-talk-swift", exact: "$version")
// target
.product(name: "ExponentialTalk", package: "exponential-talk-swift")
\`\`\`

\`\`\`swift
import ExponentialTalk

let encoder = try TalkEncoder(rate: 16000, bitrate: 24000, lossPercent: 10)
let packet = try encoder.encode(pcm: frame)  // one 20 ms frame of i16 PCM
\`\`\`

Kotlin: \`at.exponential:etalk:$version\` on Maven Central. Licence: see
LICENSE and NOTICE. Generated from the Exponential monorepo
(\`apps/desktop/crates/etalk-ffi\`, tag \`etalk-v$version\`); issues and
changes go there.
MD

echo "wrote $pkg ($([ "$local" = "--local" ] && echo "local path binary" || echo "$url"))"
echo "$zip"
echo "checksum $checksum"
