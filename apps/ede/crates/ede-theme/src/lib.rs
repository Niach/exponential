/// The first line of every generated file (behind the file's comment sign).
pub const MARKER: &str = "generated by ede-theme (eDE); edits are overwritten, `ede-theme remove` puts the previous file back";

const TOKENS: &str = include_str!("../../../../../packages/design-tokens/tokens.json");

/// An sRGB colour.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Rgb(pub u8, pub u8, pub u8);

impl Rgb {
    pub fn hex(self) -> String {
        format!("#{:02x}{:02x}{:02x}", self.0, self.1, self.2)
    }
    /// `#AARRGGBB`, what the qtct colour files hold.
    pub fn argb(self) -> String {
        format!("#ff{:02x}{:02x}{:02x}", self.0, self.1, self.2)
    }
    fn lighten(self, by: u8) -> Rgb {
        Rgb(self.0.saturating_add(by), self.1.saturating_add(by), self.2.saturating_add(by))
    }
}

/// `oklch(L C H)` or `oklch(L C H / A%)` → sRGB; an alpha is blended over
/// `over` (the tokens' `border` and `input` are white at 10 % and 15 %).
pub fn oklch(text: &str, over: Rgb) -> Option<Rgb> {
    let inner = text.trim().strip_prefix("oklch(")?.strip_suffix(')')?;
    let (lch, alpha) = match inner.split_once('/') {
        Some((lch, a)) => (lch, a.trim().trim_end_matches('%').parse::<f64>().ok()? / 100.0),
        None => (inner, 1.0),
    };
    let parts: Vec<f64> = lch.split_whitespace().map(|p| p.parse().ok()).collect::<Option<_>>()?;
    let [l, c, h] = parts[..] else { return None };
    let (a, b) = (c * h.to_radians().cos(), c * h.to_radians().sin());
    let (l_, m_, s_) = (l + 0.3963377774 * a + 0.2158037573 * b, l - 0.1055613458 * a - 0.0638541728 * b, l - 0.0894841775 * a - 1.2914855480 * b);
    let (ll, mm, ss) = (l_.powi(3), m_.powi(3), s_.powi(3));
    let lin = [
        4.0767416621 * ll - 3.3077115913 * mm + 0.2309699292 * ss,
        -1.2684380046 * ll + 2.6097574011 * mm - 0.3413193965 * ss,
        -0.0041960863 * ll - 0.7034186147 * mm + 1.7076147010 * ss,
    ];
    let gamma = |c: f64| {
        let c = c.clamp(0.0, 1.0);
        if c > 0.0031308 { 1.055 * c.powf(1.0 / 2.4) - 0.055 } else { 12.92 * c }
    };
    let channel = |i: usize, base: u8| ((gamma(lin[i]) * alpha + (base as f64 / 255.0) * (1.0 - alpha)) * 255.0).round() as u8;
    Some(Rgb(channel(0, over.0), channel(1, over.1), channel(2, over.2)))
}

fn hex(text: &str) -> Option<Rgb> {
    let h = text.trim().strip_prefix('#')?;
    let v = u32::from_str_radix(h.get(..6)?, 16).ok()?;
    Some(Rgb((v >> 16) as u8, (v >> 8) as u8, v as u8))
}

/// The palette the generated themes use, from the tokens.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Palette {
    pub background: Rgb,
    pub foreground: Rgb,
    pub card: Rgb,
    pub popover: Rgb,
    pub primary: Rgb,
    pub primary_foreground: Rgb,
    pub secondary: Rgb,
    pub muted_foreground: Rgb,
    pub destructive: Rgb,
    /// `border` (white at 10 %) over the card.
    pub border: Rgb,
    /// `input` (white at 15 %) over the card.
    pub input: Rgb,
    pub ring: Rgb,
    pub sidebar: Rgb,
    pub green: Rgb,
    pub yellow: Rgb,
    pub red: Rgb,
    pub blue: Rgb,
}

impl Palette {
    /// The tokens compiled in.
    pub fn from_tokens() -> Palette {
        Self::parse(TOKENS).expect("packages/design-tokens/tokens.json parses")
    }

    pub fn parse(tokens: &str) -> Option<Palette> {
        let v: serde_json::Value = serde_json::from_str(tokens).ok()?;
        let p = &v["palette"];
        let s = &v["semantic"];
        let card = oklch(p["card"].as_str()?, Rgb(0, 0, 0))?;
        let colour = |key: &str| oklch(p[key].as_str()?, card);
        Some(Palette {
            background: colour("background")?,
            foreground: colour("foreground")?,
            card,
            popover: colour("popover")?,
            primary: colour("primary")?,
            primary_foreground: colour("primaryForeground")?,
            secondary: colour("secondary")?,
            muted_foreground: colour("mutedForeground")?,
            destructive: colour("destructive")?,
            border: colour("border")?,
            input: colour("input")?,
            ring: colour("ring")?,
            sidebar: colour("sidebar")?,
            green: hex(s["green"].as_str()?)?,
            yellow: hex(s["yellow"].as_str()?)?,
            red: hex(s["red"].as_str()?)?,
            blue: hex(s["blue"].as_str()?)?,
        })
    }
}

/// What is installed, as far as the choice needs: theme directories and
/// font families. [`Installed::scan`] reads the machine; tests build one.
#[derive(Debug, Default, Clone)]
pub struct Installed {
    pub gtk_themes: Vec<String>,
    pub icon_themes: Vec<String>,
    pub cursor_themes: Vec<String>,
    pub fonts: Vec<String>,
    pub qt5ct: bool,
    pub qt6ct: bool,
}

impl Installed {
    pub fn scan(paths: &Paths) -> Installed {
        let mut roots: Vec<PathBuf> = vec![paths.home.join(".local/share"), paths.home.join(".themes"), paths.home.join(".icons")];
        let data_dirs = std::env::var("XDG_DATA_DIRS").ok().filter(|d| !d.is_empty()).unwrap_or_else(|| "/usr/local/share:/usr/share".into());
        roots.extend(data_dirs.split(':').map(PathBuf::from));
        let mut installed = Installed { qt5ct: on_path("qt5ct"), qt6ct: on_path("qt6ct"), ..Default::default() };
        for root in &roots {
            for (dir, list, probe) in [
                ("themes", &mut installed.gtk_themes, "gtk-3.0"),
                ("icons", &mut installed.icon_themes, "index.theme"),
                ("icons", &mut installed.cursor_themes, "cursors"),
            ] {
                let base = if root.ends_with(".themes") || root.ends_with(".icons") { root.clone() } else { root.join(dir) };
                if root.ends_with(".themes") && dir != "themes" || root.ends_with(".icons") && dir != "icons" {
                    continue;
                }
                let Ok(entries) = fs::read_dir(&base) else { continue };
                for e in entries.flatten() {
                    let name = e.file_name().to_string_lossy().into_owned();
                    if e.path().join(probe).exists() && !list.contains(&name) {
                        list.push(name);
                    }
                }
            }
        }
        if let Ok(out) = Command::new("fc-list").args([":", "family"]).output() {
            for line in String::from_utf8_lossy(&out.stdout).lines() {
                for family in line.split(',') {
                    let family = family.trim().to_string();
                    if !family.is_empty() && !installed.fonts.contains(&family) {
                        installed.fonts.push(family);
                    }
                }
            }
        }
        installed
    }
}

fn on_path(bin: &str) -> bool {
    std::env::var_os("PATH").map(|p| std::env::split_paths(&p).any(|d| d.join(bin).is_file())).unwrap_or(false)
}

/// `[theme]` of `compositor.toml`.
#[derive(Debug, Default, Clone, PartialEq)]
pub struct Overrides {
    pub bridge: bool,
    pub gtk: Option<String>,
    pub icons: Option<String>,
    pub cursor: Option<String>,
    pub cursor_size: Option<u32>,
    pub font: Option<String>,
    pub monospace: Option<String>,
    pub font_size: Option<u32>,
}

impl Overrides {
    pub fn from_config(text: &str) -> Overrides {
        let table = text.parse::<toml::Table>().unwrap_or_default();
        let theme = table.get("theme").and_then(|v| v.as_table()).cloned().unwrap_or_default();
        let s = |k: &str| theme.get(k).and_then(|v| v.as_str()).filter(|v| !v.is_empty()).map(String::from);
        let n = |k: &str| theme.get(k).and_then(|v| v.as_integer()).filter(|v| *v > 0).map(|v| v as u32);
        Overrides {
            bridge: theme.get("bridge").and_then(|v| v.as_bool()).unwrap_or(true),
            gtk: s("gtk"),
            icons: s("icons"),
            cursor: s("cursor"),
            cursor_size: n("cursor_size"),
            font: s("font"),
            monospace: s("monospace"),
            font_size: n("font_size"),
        }
    }

    pub fn read(paths: &Paths) -> Overrides {
        Self::from_config(&fs::read_to_string(paths.config.join("ede/compositor.toml")).unwrap_or_default())
    }
}

/// The names the generated files carry.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Choice {
    pub gtk: String,
    pub icons: String,
    pub cursor: String,
    pub cursor_size: u32,
    pub font: String,
    pub monospace: String,
    pub font_size: u32,
    /// `QT_QPA_PLATFORMTHEME`: `qt6ct`, `qt5ct` or Qt's own `gtk3`.
    pub qt_platform_theme: String,
}

/// Preferences, best first; the first installed wins, the last is the
/// fallback when nothing is. The shell's launcher searches the same icon
/// themes (`apps.rs`), so the menu and GTK agree.
pub const GTK_THEMES: &[&str] = &["Adwaita-dark", "Yaru-dark", "Adwaita"];
pub const ICON_THEMES: &[&str] = &["Papirus-Dark", "Papirus", "Yaru", "Adwaita", "breeze-dark", "hicolor"];
pub const CURSOR_THEMES: &[&str] = &["Bibata-Modern-Classic", "Adwaita", "Yaru", "DMZ-White", "default"];
pub const FONTS: &[&str] = &["Inter", "Ubuntu Sans", "Cantarell", "Noto Sans", "DejaVu Sans", "sans-serif"];
pub const MONOSPACE: &[&str] = &["JetBrains Mono", "Ubuntu Sans Mono", "Ubuntu Mono", "Noto Sans Mono", "DejaVu Sans Mono", "monospace"];

fn pick(prefer: Option<&String>, list: &[&str], installed: &[String]) -> String {
    if let Some(p) = prefer {
        return p.clone();
    }
    list.iter().find(|t| installed.iter().any(|i| i == *t)).or(list.last()).map(|s| s.to_string()).unwrap_or_default()
}

impl Choice {
    pub fn resolve(overrides: &Overrides, installed: &Installed) -> Choice {
        Choice {
            gtk: pick(overrides.gtk.as_ref(), GTK_THEMES, &installed.gtk_themes),
            icons: pick(overrides.icons.as_ref(), ICON_THEMES, &installed.icon_themes),
            cursor: pick(overrides.cursor.as_ref(), CURSOR_THEMES, &installed.cursor_themes),
            cursor_size: overrides.cursor_size.unwrap_or(24),
            font: pick(overrides.font.as_ref(), FONTS, &installed.fonts),
            monospace: pick(overrides.monospace.as_ref(), MONOSPACE, &installed.fonts),
            font_size: overrides.font_size.unwrap_or(10),
            qt_platform_theme: if installed.qt6ct { "qt6ct" } else if installed.qt5ct { "qt5ct" } else { "gtk3" }.into(),
        }
    }

    /// One line for the Theme page.
    pub fn summary(&self) -> String {
        format!("GTK {} · icons {} · cursor {} {} px · {} {} · Qt via {}", self.gtk, self.icons, self.cursor, self.cursor_size, self.font, self.font_size, self.qt_platform_theme)
    }
}

/// Where the files go.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Paths {
    pub home: PathBuf,
    /// `$XDG_CONFIG_HOME`.
    pub config: PathBuf,
    /// `$XDG_STATE_HOME`.
    pub state: PathBuf,
}

impl Paths {
    pub fn from_env() -> Paths {
        let home = std::env::var_os("HOME").map(PathBuf::from).unwrap_or_else(|| PathBuf::from("/"));
        let xdg = |var: &str, default: &str| std::env::var_os(var).filter(|v| !v.is_empty()).map(PathBuf::from).unwrap_or_else(|| home.join(default));
        Paths { config: xdg("XDG_CONFIG_HOME", ".config"), state: xdg("XDG_STATE_HOME", ".local/state"), home }
    }

    pub fn under(home: &Path) -> Paths {
        Paths { home: home.to_path_buf(), config: home.join(".config"), state: home.join(".local/state") }
    }

    pub fn env_file(&self) -> PathBuf {
        self.config.join("environment.d/90-ede-theme.conf")
    }

    fn before(&self) -> PathBuf {
        self.state.join("ede/theme-before.json")
    }
}

