    #[test]
    fn apply_moves_a_persons_file_aside_and_remove_puts_it_back() {
        let home = tempfile::tempdir().unwrap();
        let paths = Paths::under(home.path());
        let own_css = paths.config.join("gtk-3.0/gtk.css");
        fs::create_dir_all(own_css.parent().unwrap()).unwrap();
        fs::write(&own_css, "* { color: red; }\n").unwrap();
        let plan = Plan::build(&paths, &Palette::from_tokens(), Choice::resolve(&Overrides::default(), &installed()));
        let files_only = Options { files_only: true };
        let written = apply(&paths, &plan, files_only).unwrap();
        assert_eq!(written.len(), plan.files.len());
        assert!(is_ours(&own_css));
        assert_eq!(fs::read_to_string(aside(&own_css)).unwrap(), "* { color: red; }\n");
        assert_eq!(environment(&paths).iter().find(|(k, _)| k == "XCURSOR_THEME").map(|(_, v)| v.as_str()), Some("Adwaita"));
        // A second apply keeps the first backup.
        apply(&paths, &plan, files_only).unwrap();
        assert_eq!(fs::read_to_string(aside(&own_css)).unwrap(), "* { color: red; }\n");
        // Someone edited our settings.ini away: it is theirs now, remove leaves it.
        let ini = paths.config.join("gtk-4.0/settings.ini");
        fs::write(&ini, "[Settings]\ngtk-theme-name=Mine\n").unwrap();
        let removed = remove(&paths, &plan, files_only).unwrap();
        assert_eq!(removed.len(), plan.files.len() - 1);
        assert_eq!(fs::read_to_string(&own_css).unwrap(), "* { color: red; }\n");
        assert!(!aside(&own_css).exists());
        assert!(fs::read_to_string(&ini).unwrap().contains("Mine"));
        assert!(!paths.env_file().exists());
        assert!(environment(&paths).is_empty());
        assert!(!paths.config.join("qt6ct").exists() && !paths.home.join(".icons").exists(), "empty directories go too");
        assert!(paths.config.join("gtk-3.0").exists(), "a directory with a person's file stays");
    }
