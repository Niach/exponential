#!/usr/bin/env bun
// #EXP-1613: contract.json → eCode's enums, constants and small rules for
// Rust (apps/desktop/crates/ecode-core), TS (src/contract.generated.ts),
// Swift (ExpCore) and Kotlin (com.exponential.app.ecode). Each language comes
// from one template, so all four agree by construction. The fixtures replay
// the larger rules (forge, pipeline, runner) on the TS reference and on
// ecode-core.
// Run with: `bun run --filter @exp/ecode generate`.

import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(__dirname, "..", "..", "..")

interface Contract {
  version: number
  provider: { values: string[] }
  capability: { values: string[]; byProvider: Record<string, string[]> }
  prState: { values: string[]; live: string[] }
  mergeability: { values: string[] }
  forgeEvent: { values: string[] }
  forgeReason: { values: string[]; codes: Record<string, string[]> }
  checkStatus: { values: string[] }
  checkConclusion: { values: string[]; failing: string[]; satisfies: string[] }
  checksState: { values: string[] }
  mergeGate: { values: string[] }
  trigger: { values: string[] }
  skip: { values: string[]; conclusions: Record<string, string> }
  runnerEvent: { values: string[] }
  pipeline: {
    file: string
    version: number
    maxJobs: number
    maxSteps: number
    maxMatrix: number
    defaultTimeoutMin: number
    maxTimeoutMin: number
    nameMax: number
    matrixEnvPrefix: string
  }
  runner: { runnerLostMs: number; queuedFlagMinutes: number; labelMax: number; os: string[]; arch: string[] }
  remote: { schemes: string[]; refreshMarginMs: number; redaction: string }
}

const c = JSON.parse(readFileSync(join(__dirname, "..", "contract.json"), "utf8")) as Contract

const words = (v: string) => v.split(/[_:.-]/).filter(Boolean)
const pascal = (v: string) => words(v).map((w) => w[0]!.toUpperCase() + w.slice(1)).join("")
const camel = (v: string) => {
  const p = pascal(v)
  return p[0]!.toLowerCase() + p.slice(1)
}
const upper = (v: string) => words(v).join("_").toUpperCase()

interface Enum {
  name: string
  doc: string
  values: string[]
}
const ENUMS: Enum[] = [
  { name: "Provider", doc: "Where a repository's forge lives.", values: c.provider.values },
  { name: "Capability", doc: "What a provider supports.", values: c.capability.values },
  { name: "PrState", doc: "A review unit's (PR's) state.", values: c.prState.values },
  { name: "Mergeability", doc: "A PR against its base.", values: c.mergeability.values },
  { name: "ForgeEvent", doc: "What a forge reports after an op.", values: c.forgeEvent.values },
  { name: "ForgeReason", doc: "Why a forge op was refused.", values: c.forgeReason.values },
  { name: "CheckStatus", doc: "One check run's (= one CI job's) status.", values: c.checkStatus.values },
  { name: "CheckConclusion", doc: "A completed check's conclusion.", values: c.checkConclusion.values },
  { name: "ChecksState", doc: "The rollup over a PR's checks.", values: c.checksState.values },
  { name: "MergeGate", doc: "What the required checks say about merging.", values: c.mergeGate.values },
  { name: "Trigger", doc: "What starts a pipeline.", values: c.trigger.values },
  { name: "Skip", doc: "Why a planned job does not run.", values: c.skip.values },
  { name: "RunnerEvent", doc: "What the runner scheduler emits.", values: c.runnerEvent.values },
]

// Every reason maps to exactly one code (checked here, so a contract edit that
// forgets one fails the generator).
const reasonCode = new Map<string, string>()
for (const [code, reasons] of Object.entries(c.forgeReason.codes)) {
  for (const reason of reasons) {
    if (reasonCode.has(reason)) throw new Error(`forgeReason ${reason} maps to two codes`)
    reasonCode.set(reason, code)
  }
}
for (const reason of c.forgeReason.values) {
  if (!reasonCode.has(reason)) throw new Error(`forgeReason ${reason} maps to no code`)
}
for (const [provider, caps] of Object.entries(c.capability.byProvider)) {
  if (!c.provider.values.includes(provider)) throw new Error(`capability.byProvider names unknown provider ${provider}`)
  for (const cap of caps) if (!c.capability.values.includes(cap)) throw new Error(`unknown capability ${cap}`)
}

const HEADER = "GENERATED by packages/ecode/scripts/generate.ts from contract.json. Do not edit by hand."
const q = (v: string) => JSON.stringify(v)

// ── Rust ────────────────────────────────────────────────────────────────

const rustEnum = (e: Enum) => `/// ${e.doc}
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
pub enum ${e.name} {
${e.values.map((v) => `    #[serde(rename = ${q(v)})]\n    ${pascal(v)},`).join("\n")}
}

impl ${e.name} {
    pub const ALL: [${e.name}; ${e.values.length}] = [${e.values.map((v) => `Self::${pascal(v)}`).join(", ")}];

    /// The wire value.
    pub fn as_str(self) -> &'static str {
        match self {
${e.values.map((v) => `            Self::${pascal(v)} => ${q(v)},`).join("\n")}
        }
    }

    /// The variant for a wire value; \`None\` for an unknown one.
    pub fn parse(value: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|v| v.as_str() == value)
    }
}

impl std::fmt::Display for ${e.name} {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.as_str())
    }
}
`

const rustSet = (ty: string, values: string[]) =>
  values.length === 0 ? "false" : `matches!(value, ${values.map((v) => `${ty}::${pascal(v)}`).join(" | ")})`

const rust = `// ${HEADER}

use serde::{Deserialize, Serialize};

pub const CONTRACT_VERSION: u32 = ${c.version};
pub const PIPELINE_FILE: &str = ${q(c.pipeline.file)};
pub const PIPELINE_VERSION: u32 = ${c.pipeline.version};
pub const PIPELINE_MAX_JOBS: usize = ${c.pipeline.maxJobs};
pub const PIPELINE_MAX_STEPS: usize = ${c.pipeline.maxSteps};
pub const PIPELINE_MAX_MATRIX: usize = ${c.pipeline.maxMatrix};
pub const PIPELINE_DEFAULT_TIMEOUT_MIN: u32 = ${c.pipeline.defaultTimeoutMin};
pub const PIPELINE_MAX_TIMEOUT_MIN: u32 = ${c.pipeline.maxTimeoutMin};
pub const PIPELINE_NAME_MAX: usize = ${c.pipeline.nameMax};
pub const MATRIX_ENV_PREFIX: &str = ${q(c.pipeline.matrixEnvPrefix)};
pub const RUNNER_LOST_MS: i64 = ${c.runner.runnerLostMs};
pub const QUEUED_FLAG_MINUTES: i64 = ${c.runner.queuedFlagMinutes};
pub const LABEL_MAX: usize = ${c.runner.labelMax};
pub const OS_LABELS: [&str; ${c.runner.os.length}] = [${c.runner.os.map(q).join(", ")}];
pub const ARCH_LABELS: [&str; ${c.runner.arch.length}] = [${c.runner.arch.map(q).join(", ")}];
pub const REMOTE_SCHEMES: [&str; ${c.remote.schemes.length}] = [${c.remote.schemes.map(q).join(", ")}];
pub const REFRESH_MARGIN_MS: i64 = ${c.remote.refreshMarginMs};
pub const REDACTION: &str = ${q(c.remote.redaction)};

${ENUMS.map(rustEnum).join("\n")}
/// Does \`provider\` support \`capability\`?
pub fn supports(provider: Provider, capability: Capability) -> bool {
    let value = capability;
    match provider {
${c.provider.values.map((p) => `        Provider::${pascal(p)} => ${rustSet("Capability", c.capability.byProvider[p] ?? [])},`).join("\n")}
    }
}

impl PrState {
    /// Open or draft: the PR can still be retargeted, merged or closed.
    pub fn is_live(self) -> bool {
        let value = self;
        ${rustSet("PrState", c.prState.live)}
    }
}

impl ForgeReason {
    /// The eCore error code (\`not_found\`, \`invalid\`, \`conflict\`, \`forbidden\`) this reason is reported as.
    pub fn code(self) -> &'static str {
        match self {
${c.forgeReason.values.map((r) => `            Self::${pascal(r)} => ${q(reasonCode.get(r)!)},`).join("\n")}
        }
    }
}

impl CheckConclusion {
    /// Does this conclusion turn a check red?
    pub fn is_failing(self) -> bool {
        let value = self;
        ${rustSet("CheckConclusion", c.checkConclusion.failing)}
    }

    /// May a job that \`needs\` a check with this conclusion start?
    pub fn satisfies(self) -> bool {
        let value = self;
        ${rustSet("CheckConclusion", c.checkConclusion.satisfies)}
    }
}

impl Skip {
    /// The conclusion a skipped job's check gets.
    pub fn conclusion(self) -> CheckConclusion {
        match self {
${c.skip.values.map((s) => `            Self::${pascal(s)} => CheckConclusion::${pascal(c.skip.conclusions[s]!)},`).join("\n")}
        }
    }
}

/// A runner label: 1..=LABEL_MAX of \`a-z 0-9 . _ -\`, starting with a letter or digit.
pub fn is_valid_label(label: &str) -> bool {
    let bytes = label.as_bytes();
    !bytes.is_empty()
        && bytes.len() <= LABEL_MAX
        && (bytes[0].is_ascii_lowercase() || bytes[0].is_ascii_digit())
        && bytes.iter().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || matches!(b, b'.' | b'_' | b'-'))
}
`

// ── TypeScript ──────────────────────────────────────────────────────────

const tsEnum = (e: Enum) => `/** ${e.doc} */
export const ${camel(e.name)}Values = [${e.values.map(q).join(", ")}] as const
export type ${e.name} = (typeof ${camel(e.name)}Values)[number]
export const parse${e.name} = (value: string): ${e.name} | null =>
  (${camel(e.name)}Values as readonly string[]).includes(value) ? (value as ${e.name}) : null
`

const ts = `// ${HEADER}

export const CONTRACT_VERSION = ${c.version}
export const PIPELINE_FILE = ${q(c.pipeline.file)}
export const PIPELINE_VERSION = ${c.pipeline.version}
export const PIPELINE_MAX_JOBS = ${c.pipeline.maxJobs}
export const PIPELINE_MAX_STEPS = ${c.pipeline.maxSteps}
export const PIPELINE_MAX_MATRIX = ${c.pipeline.maxMatrix}
export const PIPELINE_DEFAULT_TIMEOUT_MIN = ${c.pipeline.defaultTimeoutMin}
export const PIPELINE_MAX_TIMEOUT_MIN = ${c.pipeline.maxTimeoutMin}
export const PIPELINE_NAME_MAX = ${c.pipeline.nameMax}
export const MATRIX_ENV_PREFIX = ${q(c.pipeline.matrixEnvPrefix)}
export const RUNNER_LOST_MS = ${c.runner.runnerLostMs}
export const QUEUED_FLAG_MINUTES = ${c.runner.queuedFlagMinutes}
export const LABEL_MAX = ${c.runner.labelMax}
export const OS_LABELS = [${c.runner.os.map(q).join(", ")}] as const
export const ARCH_LABELS = [${c.runner.arch.map(q).join(", ")}] as const
export const REMOTE_SCHEMES = [${c.remote.schemes.map(q).join(", ")}] as const
export const REFRESH_MARGIN_MS = ${c.remote.refreshMarginMs}
export const REDACTION = ${q(c.remote.redaction)}

${ENUMS.map(tsEnum).join("\n")}
const CAPABILITIES: Record<Provider, readonly Capability[]> = {
${c.provider.values.map((p) => `  ${p}: [${(c.capability.byProvider[p] ?? []).map(q).join(", ")}],`).join("\n")}
}
const LIVE: readonly PrState[] = [${c.prState.live.map(q).join(", ")}]
const REASON_CODES: Record<ForgeReason, string> = {
${c.forgeReason.values.map((r) => `  ${r}: ${q(reasonCode.get(r)!)},`).join("\n")}
}
const FAILING: readonly CheckConclusion[] = [${c.checkConclusion.failing.map(q).join(", ")}]
const SATISFIES: readonly CheckConclusion[] = [${c.checkConclusion.satisfies.map(q).join(", ")}]
const SKIP_CONCLUSIONS: Record<Skip, CheckConclusion> = {
${c.skip.values.map((s) => `  ${s}: ${q(c.skip.conclusions[s]!)},`).join("\n")}
}

/** Does \`provider\` support \`capability\`? */
export const supports = (provider: Provider, capability: Capability): boolean => CAPABILITIES[provider].includes(capability)
/** Open or draft: the PR can still be retargeted, merged or closed. */
export const isLive = (state: PrState): boolean => LIVE.includes(state)
/** The eCore error code this reason is reported as. */
export const reasonCode = (reason: ForgeReason): string => REASON_CODES[reason]
/** Does this conclusion turn a check red? */
export const isFailingConclusion = (conclusion: CheckConclusion): boolean => FAILING.includes(conclusion)
/** May a job that \`needs\` a check with this conclusion start? */
export const satisfiesNeeds = (conclusion: CheckConclusion): boolean => SATISFIES.includes(conclusion)
/** The conclusion a skipped job's check gets. */
export const skipConclusion = (skip: Skip): CheckConclusion => SKIP_CONCLUSIONS[skip]

/** A runner label: 1..LABEL_MAX of \`a-z 0-9 . _ -\`, starting with a letter or digit. */
export const isValidLabel = (label: string): boolean => label.length <= LABEL_MAX && /^[a-z0-9][a-z0-9._-]*$/.test(label)
`

// ── Swift ───────────────────────────────────────────────────────────────

const SWIFT_KEYWORDS = new Set(["open", "internal", "default", "public", "private", "case", "in", "is", "as", "if"])
const swiftCase = (v: string) => (SWIFT_KEYWORDS.has(camel(v)) ? `\`${camel(v)}\`` : camel(v))
const swiftEnum = (e: Enum) => `    /// ${e.doc}
    public enum ${e.name}: String, CaseIterable, Codable, Sendable {
${e.values.map((v) => `        case ${swiftCase(v)} = ${q(v)}`).join("\n")}
    }
`
const swiftList = (ty: string, values: string[]) => `([${values.map((v) => `.${swiftCase(v)}`).join(", ")}] as [${ty}])`

const swift = `// ${HEADER}

import Foundation

/// eCode (#EXP-1612): git and CI as one library; the contract's enums and small rules.
public enum ECode {
    public static let contractVersion = ${c.version}
    public static let pipelineFile = ${q(c.pipeline.file)}
    public static let pipelineDefaultTimeoutMin = ${c.pipeline.defaultTimeoutMin}
    public static let pipelineMaxTimeoutMin = ${c.pipeline.maxTimeoutMin}
    public static let runnerLostMs: Int64 = ${c.runner.runnerLostMs}
    public static let queuedFlagMinutes = ${c.runner.queuedFlagMinutes}
    public static let labelMax = ${c.runner.labelMax}
    public static let osLabels = [${c.runner.os.map(q).join(", ")}]
    public static let archLabels = [${c.runner.arch.map(q).join(", ")}]
    public static let redaction = ${q(c.remote.redaction)}

${ENUMS.map(swiftEnum).join("\n")}
    /// Does \`provider\` support \`capability\`?
    public static func supports(_ provider: Provider, _ capability: Capability) -> Bool {
        switch provider {
${c.provider.values.map((p) => `        case .${swiftCase(p)}: return ${swiftList("Capability", c.capability.byProvider[p] ?? [])}.contains(capability)`).join("\n")}
        }
    }

    /// Open or draft: the PR can still be retargeted, merged or closed.
    public static func isLive(_ state: PrState) -> Bool {
        ${swiftList("PrState", c.prState.live)}.contains(state)
    }

    /// Does this conclusion turn a check red?
    public static func isFailing(_ conclusion: CheckConclusion) -> Bool {
        ${swiftList("CheckConclusion", c.checkConclusion.failing)}.contains(conclusion)
    }

    /// May a job that \`needs\` a check with this conclusion start?
    public static func satisfiesNeeds(_ conclusion: CheckConclusion) -> Bool {
        ${swiftList("CheckConclusion", c.checkConclusion.satisfies)}.contains(conclusion)
    }
}
`

// ── Kotlin ──────────────────────────────────────────────────────────────

const kotlinEnum = (e: Enum) => `    /** ${e.doc} */
    enum class ${e.name}(val wire: String) {
${e.values.map((v) => `        ${upper(v)}(${q(v)}),`).join("\n")}
        ;

        companion object {
            fun parse(value: String): ${e.name}? = entries.firstOrNull { it.wire == value }
        }
    }
`
const kotlinSet = (ty: string, values: string[]) => `setOf(${values.map((v) => `${ty}.${upper(v)}`).join(", ")})`

const kotlin = `// ${HEADER}
package com.exponential.app.ecode

/** eCode (#EXP-1612): git and CI as one library; the contract's enums and small rules. */
object ECode {
    const val CONTRACT_VERSION = ${c.version}
    const val PIPELINE_FILE = ${q(c.pipeline.file)}
    const val PIPELINE_DEFAULT_TIMEOUT_MIN = ${c.pipeline.defaultTimeoutMin}
    const val PIPELINE_MAX_TIMEOUT_MIN = ${c.pipeline.maxTimeoutMin}
    const val RUNNER_LOST_MS = ${c.runner.runnerLostMs}L
    const val QUEUED_FLAG_MINUTES = ${c.runner.queuedFlagMinutes}
    const val LABEL_MAX = ${c.runner.labelMax}
    val OS_LABELS = listOf(${c.runner.os.map(q).join(", ")})
    val ARCH_LABELS = listOf(${c.runner.arch.map(q).join(", ")})
    const val REDACTION = ${q(c.remote.redaction)}

${ENUMS.map(kotlinEnum).join("\n")}
    /** Does [provider] support [capability]? */
    fun supports(provider: Provider, capability: Capability): Boolean =
        when (provider) {
${c.provider.values.map((p) => `            Provider.${upper(p)} -> ${kotlinSet("Capability", c.capability.byProvider[p] ?? [])}`).join("\n")}
        }.contains(capability)

    /** Open or draft: the PR can still be retargeted, merged or closed. */
    fun isLive(state: PrState): Boolean = state in ${kotlinSet("PrState", c.prState.live)}

    /** Does this conclusion turn a check red? */
    fun isFailing(conclusion: CheckConclusion): Boolean = conclusion in ${kotlinSet("CheckConclusion", c.checkConclusion.failing)}

    /** May a job that \`needs\` a check with this conclusion start? */
    fun satisfiesNeeds(conclusion: CheckConclusion): Boolean = conclusion in ${kotlinSet("CheckConclusion", c.checkConclusion.satisfies)}
}
`

