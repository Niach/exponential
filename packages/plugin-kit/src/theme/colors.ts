import { readFileSync } from "node:fs"

// The semantic status colours (design-tokens `semantic`) for an adapter that
// draws its own elements: rendered into `model/core/colors.ts`, which the
// Claude Code mods and later the pi widgets read.

const TOKENS = new URL(`../../../design-tokens/tokens.json`, import.meta.url)
const TONES = [`neutral`, `yellow`, `green`, `red`, `orange`, `blue`] as const

export function renderToneColors(): string {
  const semantic = JSON.parse(readFileSync(TOKENS, `utf8`)).semantic as Record<string, string>
  const rows = TONES.map((tone) => {
    if (!/^#[0-9A-Fa-f]{6}$/.test(semantic[tone] ?? ``)) throw new Error(`design-tokens semantic.${tone} is not #rrggbb`)
    return `  ${tone}: \`${semantic[tone]}\`,`
  })
  return `// GENERATED by packages/plugin-kit (bun run --filter @exp/plugin-kit generate)
// from packages/design-tokens/tokens.json \`semantic\`. Do not edit.
import type { Tone } from "./issue"

export const TONE_COLOR: Record<Tone, string> = {
${rows.join(`\n`)}
}
`
}
