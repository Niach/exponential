export type MetricKind = `ms` | `count` | `bytes` | `mb`

export interface MetricDef {
  id: string
  kind: MetricKind
  /** What the number is; every runner measures it the way this sentence says. */
  what: string
  /** A renderer that cannot measure it leaves it out (counters behind a debug flag, memory). */
  optional?: boolean
}

/** `item` templates: `{i}` = the index, `{i % N}` = the index modulo N (bench-list.json's spec); every field a string. */
export interface GeneratedData {
  generate: { path: string; count: number; item: Record<string, string> }
}

export interface ScenarioDef {
  id: string
  title: string
  /** What the scenario exercises and where a renderer typically loses time. */
  what: string
  theme: string
  mode: `light` | `dark`
  viewport: { width: number; height: number }
  surface: { nested: NestedNode } | { components: FlatComponent[] }
  data?: Record<string, unknown> | GeneratedData
  /** The steps a runner performs after the first paint (scenario-specific). */
  steps: Record<string, unknown>
  metrics: MetricDef[]
}

