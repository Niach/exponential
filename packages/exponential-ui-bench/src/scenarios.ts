export function manifest() {
  return {
    $comment: `${HEADER} The Exponential UI benchmark suite (VAPP-105): one file per scenario under scenarios/, each naming its metrics. A runner (runners/, the core's and gpui's examples/bench_suite.rs, Swift's BenchSuiteTests, Compose's BenchSuiteTest) reports every scenario's non-optional metrics into a result fragment (src/results.ts); results/<machine>.json commits them per machine; budgets.json + scripts/ratchet.ts gate CI.`,
    version: MANIFEST_VERSION,
    renderers: RENDERERS,
    scenarios: SCENARIOS.map((s) => ({ id: s.id, title: s.title, what: s.what, file: `scenarios/${s.id}.json`, metrics: s.metrics })),
  }
}

export function scenarioFile(s: ScenarioDef) {
  return {
    $comment: `${HEADER} ${s.title}: ${s.what}`,
    id: s.id,
    theme: s.theme,
    mode: s.mode,
    catalogId: CORE_CATALOG_ID,
    viewport: s.viewport,
    surface: s.surface,
    ...(s.data ? { data: s.data } : {}),
    steps: s.steps,
    metrics: s.metrics.map((m) => m.id),
  }
}

export function renderScenarios(): Record<string, string> {
  const json = (v: unknown) => `${JSON.stringify(v, null, 2)}\n`
  const files: Record<string, string> = { "scenarios/manifest.json": json(manifest()) }
  for (const s of SCENARIOS) files[`scenarios/${s.id}.json`] = json(scenarioFile(s))
  return files
}

/** Expand a `generate` spec into its items (every runner ports this): every
 *  field is a STRING (bench-list.json's `meta` = String(i % 97)). */
export function generateItems(spec: GeneratedData[`generate`]): Record<string, string>[] {
  const fill = (template: string, i: number): string => template.replace(/\{i % (\d+)\}/g, (_, n) => String(i % Number(n))).replace(/\{i\}/g, String(i))
  return Array.from({ length: spec.count }, (_, i) => Object.fromEntries(Object.entries(spec.item).map(([k, t]) => [k, fill(t, i)])))
}
