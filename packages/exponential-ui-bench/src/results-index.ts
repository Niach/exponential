// VAPP-105: results/index.ts, the static import list of every committed
// results file (ui.exponential.at's Numbers page prerenders under Bun, so it
// imports a static list rather than globbing). `scripts/run.ts` and
// `scripts/generate.ts` regenerate it; generate.test.ts gates drift.
import { readdirSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { BENCH_ROOT } from "./results"

export function resultsIndexSource(): string {
  const files = readdirSync(join(BENCH_ROOT, `results`))
    .filter((f) => f.endsWith(`.json`))
    .sort()
  const names = files.map((_, i) => `r${i}`)
  return [
    `// AUTO-GENERATED by packages/exponential-ui-bench/scripts/generate.ts (and scripts/run.ts) — do not edit.`,
    `// Every committed results file, for ui.exponential.at's Numbers page.`,
    `import type { ResultsFile } from "../src/results"`,
    ...files.map((f, i) => `import ${names[i]} from "./${f}"`),
    ``,
    `export const RESULTS: readonly ResultsFile[] = [${names.join(`, `)}] as unknown as ResultsFile[]`,
    ``,
  ].join(`\n`)
}

export function writeResultsIndex(): string {
  const path = join(BENCH_ROOT, `results`, `index.ts`)
  writeFileSync(path, resultsIndexSource())
  return path
}
