#!/usr/bin/env bun
// VAPP-108: scores every recorded fixture and writes eval/report.json (the
// numbers the issue, the site's /eval/ page and eval.test.ts read). Pure:
// no model, no browser. render.ts, natives.ts and parity.ts add their
// sections to the same report; this script keeps them when present.
// VAPP-127: it also writes eval/eval-specimens.json, every surface as the native
// specimen the example apps and the IDE paint by id (the shots pipeline's
// `eval` lane).
//
//   bun eval/score.ts [--print]

import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { join, resolve } from "node:path"
import budget from "../fixtures/prompt-budget.json" with { type: "json" }
import corpus from "./corpus.json" with { type: "json" }
import { CORE_CATALOG_ID } from "../src/catalog"
import { aggregate, evalSpecimens, scoreFixture, type Aggregate, type Corpus, type EvalFixture, type EvalSpecimen, type ScoreRow } from "./lib"

export const REPORT_PATH = join(import.meta.dir, `report.json`)
export const SPECIMENS_PATH = join(import.meta.dir, `eval-specimens.json`)
const FIXTURES = join(import.meta.dir, `fixtures`)

export interface EvalReport {
  $comment: string
  prompt: typeof budget
  aggregate: Aggregate
  rows: ScoreRow[]
  /** render.ts: what the web render measured per surface × width. */
  render?: unknown
  /** natives.ts (VAPP-127): what the native renders measured per surface × platform. */
  natives?: unknown
  /** parity.ts: the Devices template vs the native page, per platform; every appView surface vs its app screen. */
  parity?: unknown
}

export interface SpecimensFile {
  $comment: string
  catalogId: string
  specimens: EvalSpecimen[]
}

/** eval/eval-specimens.json: the fixtures as native specimens (same shape as fixtures/specimens.json, plus `data`). */
export function buildSpecimens(): SpecimensFile {
  return {
    $comment: `AUTO-GENERATED by packages/exponential-ui/eval/score.ts (VAPP-127) — do not edit. Every recorded eval surface as a native specimen: the nested tree and the data model render.ts hands the web harnesses, keyed \`exponential-ui-eval-<corpus id>\`. The Compose example (\`--es shot\`), the Swift example (\`-shot\`) and the IDE (\`EXP_DEV_SCREEN\`) paint one by id; \`bun run shots -- --platform <p> --views eval:<id>\` captures it into eval/out/<id>/<platform>.webp.`,
    catalogId: CORE_CATALOG_ID,
    specimens: evalSpecimens(corpus as Corpus, readFixture),
  }
}

export function readFixture(id: string, dir: string = FIXTURES): EvalFixture | undefined {
  const file = join(dir, `${id}.json`)
  if (!existsSync(file)) return undefined
  const { $comment: _, ...fixture } = JSON.parse(readFileSync(file, `utf8`)) as EvalFixture & { $comment?: string }
  return fixture
}

/** Every corpus prompt scored against its fixture (missing fixtures are
 *  reported, never scored). */
export function scoreAll(dir: string = FIXTURES): { rows: ScoreRow[]; missing: string[] } {
  const rows: ScoreRow[] = []
  const missing: string[] = []
  for (const entry of (corpus as Corpus).prompts) {
    const fixture = readFixture(entry.id, dir)
    if (!fixture) missing.push(entry.id)
    else rows.push(scoreFixture(entry, fixture))
  }
  return { rows, missing }
}

export function buildReport(previous?: Partial<EvalReport>): EvalReport {
  const { rows, missing } = scoreAll()
  if (missing.length) throw new Error(`no fixture for: ${missing.join(`, `)} (bun eval/record.ts)`)
  return {
    $comment: `AUTO-GENERATED by packages/exponential-ui/eval/score.ts (VAPP-108) — do not edit. The ergonomics eval on record: the prompt sizes, the aggregate over eval/corpus.json × eval/fixtures/*.json (validator issues, tokens, the visual rubric, spacing rhythm, the vocabulary the corpus used), one row per surface, and what render.ts / parity.ts measured. eval.test.ts fails when the rows drift from the fixtures without a rerun.`,
    prompt: budget,
    aggregate: aggregate(rows),
    rows,
    ...(previous?.render !== undefined ? { render: previous.render } : {}),
    ...(previous?.natives !== undefined ? { natives: previous.natives } : {}),
    ...(previous?.parity !== undefined ? { parity: previous.parity } : {}),
  }
}

export function readReport(): EvalReport | undefined {
  return existsSync(REPORT_PATH) ? (JSON.parse(readFileSync(REPORT_PATH, `utf8`)) as EvalReport) : undefined
}

export function printSummary(report: EvalReport): string {
  const a = report.aggregate
  const pct = (n: number, d: number) => (d ? `${Math.round((n / d) * 100)}%` : `–`)
  const lines = [
    `surfaces ${a.surfaces} (${Object.entries(a.recordedBy).map(([k, v]) => `${v} ${k}`).join(`, `)})`,
    `prompt full ${report.prompt.full.chars} chars ≈ ${report.prompt.full.tokens} tokens; terse ${report.prompt.terse.tokens}; lite ${report.prompt.lite.tokens}`,
    `validator clean ${a.validatorClean}/${a.surfaces}; ${a.issuesTotal} issues; top: ${a.issueKinds.slice(0, 3).map((k) => `${k.message} ×${k.count}`).join(`; `)}`,
    `components mean ${a.components.mean} (max ${a.components.max}); depth mean ${a.depth.mean} (max ${a.depth.max})`,
    `tokens in ${a.tokens.input} / out ${a.tokens.output} (mean out ${a.tokens.meanOutput}${a.tokens.estimated ? `, estimated` : ``})`,
    `rubric ${Object.entries(a.rubric).map(([k, v]) => `${k} ${v.passed}/${v.expected} (${pct(v.passed, v.expected)})`).join(`, `)}`,
    `spacing rhythm ${a.spacing.rhythm} (${a.spacing.surfacesWithRawPx} surfaces with raw px); unaligned rows ${a.unalignedRows}; authored Boxes ${a.boxes}`,
    `vocabulary top: ${a.vocabulary.slice(0, 8).map((v) => `${v.component} ${v.surfaces}`).join(`, `)}; unused ${a.unused.length}`,
  ]
  return lines.join(`\n`)
}

/** VAPP-128: `--fixtures <dir>` scores another recording of the corpus
 *  (e.g. eval/baseline-1181/, the same fixture shape) and prints its summary
 *  without touching report.json: the before side of a before/after. */
const fixturesArg = process.argv.indexOf(`--fixtures`)
if (import.meta.main && fixturesArg >= 0) {
  const dir = resolve(process.argv[fixturesArg + 1] ?? ``)
  const { rows, missing } = scoreAll(dir)
  if (missing.length) throw new Error(`${dir}: no fixture for ${missing.join(`, `)}`)
  console.log(printSummary({ ...(readReport() ?? buildReport()), aggregate: aggregate(rows), rows }))
} else if (import.meta.main) {
  const report = buildReport(readReport())
  writeFileSync(REPORT_PATH, `${JSON.stringify(report, null, 2)}\n`)
  writeFileSync(SPECIMENS_PATH, `${JSON.stringify(buildSpecimens(), null, 2)}\n`)
  console.log(printSummary(report))
  console.log(`→ ${REPORT_PATH}, ${SPECIMENS_PATH}`)
}
