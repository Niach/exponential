"""Builds `Inter Symbols`: the desktop's Inter subset to the key symbols of
`inter-symbols.json`, one face per weight, and writes every copy the
renderers bundle. Reproducible (pinned fonttools, timestamps kept):

    uvx --from 'fonttools[woff]==4.69.1' python -I packages/exponential-ui/fonts/build.py

Then commit the fonts, `inter-symbols.json` (sha256s) and
`src/web/inter-symbols.generated.ts`.
"""

import base64
import hashlib
import io
import json
import os
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
SPEC_PATH = os.path.join(REPO, "packages/exponential-ui/fonts/inter-symbols.json")
LICENCE = "packages/exponential-ui/fonts/OFL-Inter.txt"

# Where each renderer bundles the faces: (directory, file name of a style).
TTF_COPIES = [
    ("packages/exponential-ui/fonts", lambda s: f"InterSymbols-{s}.ttf"),
    ("packages/exponential-ui-swift/Sources/ExponentialUI/Resources/Fonts", lambda s: f"InterSymbols-{s}.ttf"),
    ("packages/exponential-ui-compose/ui-compose/src/main/res/font", lambda s: f"inter_symbols_{s.lower()}.ttf"),
    ("apps/desktop/crates/eui-gpui/assets/fonts", lambda s: f"InterSymbols-{s}.ttf"),
]
WOFF2_DIR = "packages/exponential-ui/fonts"
LICENCE_COPIES = [
    "packages/exponential-ui-swift/Sources/ExponentialUI/Resources/Fonts/OFL-Inter.txt",
    "packages/exponential-ui-compose/ui-compose/OFL-Inter.txt",
    "apps/desktop/crates/eui-gpui/assets/fonts/OFL-Inter.txt",
]
GENERATED_TS = "packages/exponential-ui/src/web/inter-symbols.generated.ts"


def codepoints_hash(cps):
    return hashlib.sha256(",".join(sorted(cps)).encode()).hexdigest()


def rename(font, family):
    """`Inter` → `Inter Symbols` in the family, full and PostScript names."""
    for rec in font["name"].names:
        text = rec.toUnicode()
        if rec.nameID in (1, 3, 4, 16, 21):
            text = text.replace("Inter", family, 1)
        elif rec.nameID == 6:
            text = text.replace("Inter", family.replace(" ", ""), 1)
        else:
            continue
        rec.string = text


def build_face(src, cps, family, flavor):
    font = TTFont(src, recalcTimestamp=False)
    options = subset.Options()
    options.hinting = False
    options.desubroutinize = True
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.notdef_outline = True
    options.recalc_timestamp = False
    options.flavor = flavor
    sub = subset.Subsetter(options)
    sub.populate(unicodes=[int(c[2:], 16) for c in cps])
    sub.subset(font)
    rename(font, family)
    font.flavor = flavor
    out = io.BytesIO()
    font.save(out, reorderTables=True)
    return out.getvalue()


def write(rel, data):
    path = os.path.join(REPO, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(data)
    return hashlib.sha256(data).hexdigest()


def main():
    with open(SPEC_PATH, encoding="utf-8") as f:
        spec = json.load(f)
    family = spec["family"]
    cps = [c["cp"] for c in spec["codepoints"]]
    carried = [c["cp"] for c in spec.get("carried", [])]
    outputs = {}
    faces_ts = []
    for face in spec["faces"]:
        src = os.path.join(REPO, spec["source"], face["from"])
        ttf = build_face(src, cps + carried, family, None)
        woff2 = build_face(src, cps + carried, family, "woff2")
        for directory, name in TTF_COPIES:
            rel = f"{directory}/{name(face['style'])}"
            outputs[rel] = write(rel, ttf)
        rel = f"{WOFF2_DIR}/InterSymbols-{face['style']}.woff2"
        outputs[rel] = write(rel, woff2)
        faces_ts.append((face["weight"], base64.b64encode(woff2).decode()))
        if len(woff2) > 10 * 1024 or len(ttf) > 10 * 1024:
            sys.exit(f"{face['style']}: {len(ttf)} B ttf / {len(woff2)} B woff2, over the 10 KB budget")
    with open(os.path.join(REPO, LICENCE), "rb") as f:
        licence = f.read()
    for rel in LICENCE_COPIES:
        outputs[rel] = write(rel, licence)

    unicode_range = ",".join(sorted(cps))
    rules = "\n".join(
        f"  `@font-face{{font-family:\"{family}\";font-style:normal;font-weight:{w};src:url(data:font/woff2;base64,{b64}) format(\"woff2\");unicode-range:{unicode_range}}}`,"
        for w, b64 in faces_ts
    )
    ts = (
        "// GENERATED by packages/exponential-ui/fonts/build.py from inter-symbols.json: do not edit.\n"
        "// `Inter Symbols` (Inter subset to the key symbols, SIL OFL 1.1, fonts/OFL-Inter.txt)\n"
        "// as @font-face rules with the woff2 inlined, so every web renderer has the\n"
        "// face without host setup (web/theme-css.ts adds them to the theme sheet).\n\n"
        f"export const INTER_SYMBOLS_WEIGHTS = [{', '.join(str(w) for w, _ in faces_ts)}] as const\n\n"
        "export const INTER_SYMBOLS_FONT_FACES: readonly string[] = [\n"
        f"{rules}\n"
        "]\n"
    )
    outputs[GENERATED_TS] = write(GENERATED_TS, ts.encode())

    spec["codepointsHash"] = codepoints_hash(cps + carried)
    spec["outputs"] = dict(sorted(outputs.items()))
    with open(SPEC_PATH, "w", encoding="utf-8") as f:
        f.write(json.dumps(spec, ensure_ascii=False, indent=2) + "\n")
    for rel, sha in sorted(outputs.items()):
        size = os.path.getsize(os.path.join(REPO, rel))
        print(f"{size:7d} B  {rel}")


if __name__ == "__main__":
    main()
