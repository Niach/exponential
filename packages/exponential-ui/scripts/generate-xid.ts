// VAPP-289 (round 9 contract §4): the UAX #31 identifier tables, read from
// the vendored Unicode 17.0.0 DerivedCoreProperties.txt into sorted code
// point ranges for every core. No platform regex engine decides an
// identifier: engines ship different Unicode versions.
//
//   generated/xid.ts                    TS (src/ids.ts re-exports isIdentifier)
//   generated/xid.rs                    Rust, copied to eui-core src/generated/xid.rs
//   generated/Xid.generated.swift       Swift
//   generated/Xid.generated.kt          Kotlin

import { readFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const pkgRoot = join(dirname(fileURLToPath(import.meta.url)), `..`)
export const UNICODE_VERSION = `17.0.0`

type Range = [number, number]

/** The merged, sorted ranges of one derived property. */
export function xidRanges(text: string, property: string): Range[] {
  const out: Range[] = []
  for (const raw of text.split(`\n`)) {
    const line = raw.replace(/#.*/, ``).trim()
    if (!line) continue
    const [cps, prop] = line.split(`;`).map((s) => s.trim())
    if (prop !== property) continue
    const [a, b] = cps.split(`..`)
    out.push([parseInt(a, 16), parseInt(b ?? a, 16)])
  }
  out.sort((x, y) => x[0] - y[0])
  const merged: Range[] = []
  for (const r of out) {
    const last = merged[merged.length - 1]
    if (last && r[0] <= last[1] + 1) last[1] = Math.max(last[1], r[1])
    else merged.push([r[0], r[1]])
  }
  return merged
}

function tables(): { start: Range[]; cont: Range[] } {
  const text = readFileSync(join(pkgRoot, `vendor/unicode/DerivedCoreProperties.txt`), `utf8`)
  if (!text.startsWith(`# DerivedCoreProperties-${UNICODE_VERSION}.txt`)) throw new Error(`vendor/unicode/DerivedCoreProperties.txt is not Unicode ${UNICODE_VERSION}`)
  return { start: xidRanges(text, `XID_Start`), cont: xidRanges(text, `XID_Continue`) }
}

const HEADER = `AUTO-GENERATED by packages/exponential-ui/scripts/generate-xid.ts — do not edit.
Source of truth: packages/exponential-ui/vendor/unicode/DerivedCoreProperties.txt (Unicode ${UNICODE_VERSION}), round 9 contract §4.
An identifier = ^[\\p{XID_Start}_][\\p{XID_Continue}]*$ over code points; the empty string is not one; no normalization.`

const hex = (n: number) => `0x${n.toString(16).toUpperCase()}`
const flat = (ranges: Range[], per = 8) => {
  const items = ranges.map(([a, b]) => `${hex(a)}, ${hex(b)}`)
  const lines: string[] = []
  for (let i = 0; i < items.length; i += per) lines.push(`  ${items.slice(i, i + per).join(`, `)},`)
  return lines.join(`\n`)
}
const pairs = (ranges: Range[], open: string, close: string, per = 6) => {
  const items = ranges.map(([a, b]) => `${open}${hex(a)}, ${hex(b)}${close}`)
  const lines: string[] = []
  for (let i = 0; i < items.length; i += per) lines.push(`    ${items.slice(i, i + per).join(`, `)},`)
  return lines.join(`\n`)
}

/** The text form `decode` in generated/xid.ts reads. */
function encode(ranges: Range[]): string {
  const digits = `0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz-_`
  let out = ``
  let at = 0
  for (const v of ranges.flat()) {
    let n = v - at
    at = v
    for (; n >= 32; n = Math.floor(n / 32)) out += digits[32 + (n % 32)]
    out += digits[n]
  }
  return out
}

function renderTs({ start, cont }: { start: Range[]; cont: Range[] }): string {
  return `// ${HEADER.split(`\n`).join(`\n// `)}

export const UNICODE_VERSION = ${JSON.stringify(UNICODE_VERSION)}

const DIGITS = \`0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz-_\`

/** VAPP-289: a table as text (the npm bundles carry it): each number of the
 *  flat ranges, as its distance from the one before, in base-32 digits low
 *  first, a digit + 32 = more follow. Back to [lo, hi, lo, hi, …], sorted. */
function decode(text: string): number[] {
  const out: number[] = []
  let at = 0
  let n = 0
  let shift = 0
  for (const ch of text) {
    const d = DIGITS.indexOf(ch)
    n |= (d & 31) << shift
    shift += 5
    if (d < 32) {
      at += n
      out.push(at)
      n = shift = 0
    }
  }
  return out
}

/** XID_Start as flat [lo, hi, lo, hi, …] inclusive ranges, sorted. */
export const XID_START: readonly number[] = decode(${JSON.stringify(encode(start))})

/** XID_Continue as flat [lo, hi, lo, hi, …] inclusive ranges, sorted. */
export const XID_CONTINUE: readonly number[] = decode(${JSON.stringify(encode(cont))})

function inRanges(table: readonly number[], cp: number): boolean {
  let lo = 0
  let hi = table.length / 2 - 1
  while (lo <= hi) {
    const mid = (lo + hi) >> 1
    if (cp < table[mid * 2]) hi = mid - 1
    else if (cp > table[mid * 2 + 1]) lo = mid + 1
    else return true
  }
  return false
}

export const isXidStart = (cp: number): boolean => inRanges(XID_START, cp)
export const isXidContinue = (cp: number): boolean => inRanges(XID_CONTINUE, cp)

/** UAX #31: ^[\\p{XID_Start}_][\\p{XID_Continue}]*$ over code points. */
export function isIdentifier(s: unknown): s is string {
  if (typeof s !== \`string\` || s.length === 0) return false
  let first = true
  for (const ch of s) {
    const cp = ch.codePointAt(0)!
    if (first) {
      if (cp !== 0x5f && !isXidStart(cp)) return false
      first = false
    } else if (!isXidContinue(cp)) return false
  }
  return true
}
`
}

function renderRust({ start, cont }: { start: Range[]; cont: Range[] }): string {
  return `// ${HEADER.split(`\n`).join(`\n// `)}
// Copied to apps/desktop/crates/eui-core/src/generated/xid.rs (drift-gated); include it as \`pub mod xid { include!("xid.rs"); }\`.

pub const UNICODE_VERSION: &str = ${JSON.stringify(UNICODE_VERSION)};

/// XID_Start, inclusive (lo, hi) ranges, sorted.
pub const XID_START: &[(u32, u32)] = &[
${pairs(start, `(`, `)`)}
];

/// XID_Continue, inclusive (lo, hi) ranges, sorted.
pub const XID_CONTINUE: &[(u32, u32)] = &[
${pairs(cont, `(`, `)`)}
];

fn in_ranges(table: &[(u32, u32)], cp: u32) -> bool {
    table
        .binary_search_by(|&(lo, hi)| {
            if cp < lo {
                core::cmp::Ordering::Greater
            } else if cp > hi {
                core::cmp::Ordering::Less
            } else {
                core::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

pub fn is_xid_start(c: char) -> bool {
    in_ranges(XID_START, c as u32)
}

pub fn is_xid_continue(c: char) -> bool {
    in_ranges(XID_CONTINUE, c as u32)
}

/// UAX #31: \`^[\\p{XID_Start}_][\\p{XID_Continue}]*$\` over code points; "" is not one.
pub fn is_identifier(s: &str) -> bool {
    let mut chars = s.chars();
    match chars.next() {
        None => false,
        Some(first) => (first == '_' || is_xid_start(first)) && chars.all(is_xid_continue),
    }
}
`
}

function renderSwift({ start, cont }: { start: Range[]; cont: Range[] }): string {
  return `// ${HEADER.split(`\n`).join(`\n// `)}

import Foundation

public enum ExponentialUIXid {
    public static let unicodeVersion: String = ${JSON.stringify(UNICODE_VERSION)}
    public static let xidStart: [(UInt32, UInt32)] = [
${pairs(start, `(`, `)`)}
    ]
    public static let xidContinue: [(UInt32, UInt32)] = [
${pairs(cont, `(`, `)`)}
    ]

    static func inRanges(_ table: [(UInt32, UInt32)], _ cp: UInt32) -> Bool {
        var lo = 0
        var hi = table.count - 1
        while lo <= hi {
            let mid = (lo + hi) / 2
            if cp < table[mid].0 { hi = mid - 1 } else if cp > table[mid].1 { lo = mid + 1 } else { return true }
        }
        return false
    }

    public static func isXidStart(_ cp: UInt32) -> Bool { inRanges(xidStart, cp) }
    public static func isXidContinue(_ cp: UInt32) -> Bool { inRanges(xidContinue, cp) }

    /// UAX #31 over code points; "" is not one.
    public static func isIdentifier(_ s: String) -> Bool {
        var first = true
        for scalar in s.unicodeScalars {
            if first {
                if scalar.value != 0x5F && !isXidStart(scalar.value) { return false }
                first = false
            } else if !isXidContinue(scalar.value) { return false }
        }
        return !first
    }
}
`
}

function renderKotlin({ start, cont }: { start: Range[]; cont: Range[] }): string {
  const ints = (ranges: Range[]) => {
    const items = ranges.map(([a, b]) => `${hex(a)}, ${hex(b)}`)
    const lines: string[] = []
    for (let i = 0; i < items.length; i += 8) lines.push(`        ${items.slice(i, i + 8).join(`, `)},`)
    return lines.join(`\n`)
  }
  return `// ${HEADER.split(`\n`).join(`\n// `)}

package at.exponential.ui

object ExponentialUIXid {
    const val unicodeVersion: String = ${JSON.stringify(UNICODE_VERSION)}

    /** XID_Start as flat [lo, hi, lo, hi, …] inclusive ranges, sorted. */
    val xidStart: IntArray = intArrayOf(
${ints(start)}
    )

    /** XID_Continue as flat [lo, hi, lo, hi, …] inclusive ranges, sorted. */
    val xidContinue: IntArray = intArrayOf(
${ints(cont)}
    )

    private fun inRanges(table: IntArray, cp: Int): Boolean {
        var lo = 0
        var hi = table.size / 2 - 1
        while (lo <= hi) {
            val mid = (lo + hi) ushr 1
            if (cp < table[mid * 2]) hi = mid - 1 else if (cp > table[mid * 2 + 1]) lo = mid + 1 else return true
        }
        return false
    }

    fun isXidStart(cp: Int): Boolean = inRanges(xidStart, cp)
    fun isXidContinue(cp: Int): Boolean = inRanges(xidContinue, cp)

    /** UAX #31 over code points; "" is not one. */
    fun isIdentifier(s: String): Boolean {
        if (s.isEmpty()) return false
        var i = 0
        var first = true
        while (i < s.length) {
            val cp = s.codePointAt(i)
            if (first) {
                if (cp != 0x5F && !isXidStart(cp)) return false
                first = false
            } else if (!isXidContinue(cp)) return false
            i += Character.charCount(cp)
        }
        return true
    }
}
`
}

/** Every xid output, keyed by its path relative to the package root. */
export function renderXid(): Record<string, string> {
  const t = tables()
  const rust = renderRust(t)
  return {
    "generated/xid.ts": renderTs(t),
    "generated/xid.rs": rust,
    "../../apps/desktop/crates/eui-core/src/generated/xid.rs": rust,
    "generated/Xid.generated.swift": renderSwift(t),
    "generated/Xid.generated.kt": renderKotlin(t),
  }
}
