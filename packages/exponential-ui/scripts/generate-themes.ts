interface DesignTokens {
  palette: Record<string, string>
  semantic: Record<string, string>
  glass: Record<string, string>
  radius: Record<string, number>
  size: Record<string, number>
  motion: { duration: Record<string, number>; ease: Record<string, [number, number, number, number]> }
  spacing: Record<string, number>
  type: { fontFamily: string; size: Record<string, number>; lineHeight: Record<string, number>; weight: Record<string, number>; emphasis: Record<string, number> }
}

/** A design-tokens group without its `$comment`. */
function numbers(group: Record<string, unknown>): Record<string, number> {
  return Object.fromEntries(Object.entries(group).filter(([k, v]) => !k.startsWith(`$`) && typeof v === `number`)) as Record<string, number>
}

function hex(value: string): `#${string}` {
  const h = toThemeHex(value)
  if (!h) throw new Error(`design token colour not parseable: ${value}`)
  return h
}

export function composeExponential(): ThemeSource {
  const design = JSON.parse(readFileSync(join(repoRoot, `packages/design-tokens/tokens.json`), `utf8`)) as DesignTokens
  const css = readFileSync(join(repoRoot, `packages/ui/src/styles.css`), `utf8`)
  const imported = importShadcnCss(css)
  const light = { ...(imported.modes.light?.color ?? {}) }
  const dark = { ...(imported.modes.dark?.color ?? {}) }
  for (const [mode, table] of [[`light`, light], [`dark`, dark]] as const) {
    for (const name of [`background`, `foreground`, `card`, `primary`, `muted`, `border`, `ring`, `chart1`])
      if (!table[name]) throw new Error(`styles.css ${mode} palette lacks --${name}`)
  }
  // The glass look: the dark surfaces are white-alpha fills over the ground
  // (packages/design-tokens `glass`), not the opaque shadcn greys.
  dark.card = hex(design.glass.fillCard)
  dark.muted = hex(design.glass.fillSection)
  dark.secondary = hex(design.glass.fillRow)
  dark.accent = hex(design.glass.fillActive)
  dark.border = hex(design.glass.strokeCard)
  dark.input = hex(design.palette.input)
  // Status semantics are fixed hues on every client (design-tokens `semantic`).
  for (const table of [light, dark]) {
    table.success = hex(design.semantic.green)
    table.warning = hex(design.semantic.yellow)
    table.info = hex(design.semantic.blue)
    table.warningForeground = `#1c1917`
    table.infoForeground = `#ffffff`
  }
  light.successForeground = `#ffffff`
  dark.successForeground = `#052e16`
  light.destructiveForeground ??= `#ffffff`
  dark.destructiveForeground ??= light.foreground
  const shadow = (a: string) => ({
    none: [],
    sm: [{ x: 0, y: 1, blur: 2, spread: 0, color: hex(`rgb(0 0 0 / ${a})`) }],
    md: [{ x: 0, y: 4, blur: 12, spread: -2, color: hex(`rgb(0 0 0 / ${a})`) }],
    lg: [{ x: 0, y: 12, blur: 32, spread: -8, color: hex(`rgb(0 0 0 / ${a})`) }],
    xl: [{ x: 0, y: 20, blur: 48, spread: -12, color: hex(`rgb(0 0 0 / ${a})`) }],
  })
  const s = design.size
  const mono = `ui-monospace`
  return {
    $schema: THEME_SCHEMA_ID,
    id: `exponential`,
    name: `Exponential`,
    extends: `neutral`,
    modes: {
      light: { color: light, shadow: shadow(`0.08`) },
      dark: { color: dark, shadow: shadow(`0.4`) },
    },
    tokens: {
      spacing: { none: 0, ...numbers(design.spacing), xl3: 48 },
      radius: { none: 0, ...numbers(design.radius), full: 9999 },
      type: {
        size: { ...numbers(design.type.size), xl3: 30 },
        lineHeight: { ...numbers(design.type.lineHeight), xl3: 36 },
        weight: numbers(design.type.weight),
        family: { sans: design.type.fontFamily, mono },
      },
      control: {
        buttonSm: s.controlSm, buttonMd: s.controlMd, buttonLg: s.controlLg, buttonIcon: s.controlMd,
        input: s.inputHeight, textarea: 64,
        row: s.rowHeight, rowCompact: 28,
        pill: s.controlSm, badge: 20, chip: s.controlSm,
        toggle: s.controlMd, switch: 20, checkbox: 16, slider: 16,
        progress: 8, meter: 8,
        avatarSm: 24, avatarMd: 32, avatarLg: 40,
        iconSm: 16, iconMd: 20, iconLg: 24,
        hairline: 1,
        appBar: 48, tabBar: 56, toast: 56,
      },
      opacity: { ...numbers(design.type.emphasis), disabled: 0.5 },
      border: { none: 0, hairline: 1, thick: 2 },
      motion: numbers(design.motion.duration),
      // Round 1: the app's easing curves (design-tokens `motion.ease`, the
      // same names) back `$ease.*`; breakpoints and density inherit neutral's.
      ease: Object.fromEntries(Object.entries(design.motion.ease).filter(([k]) => !k.startsWith(`$`))) as Record<string, [number, number, number, number]>,
    },
    fonts: {
      [design.type.fontFamily]: { fallback: `ui-sans-serif, system-ui, sans-serif`, weights: [400, 500, 600, 700], source: `host` },
      [mono]: { fallback: `SFMono-Regular, Menlo, Consolas, monospace`, source: `system` },
    },
    recipes: exponentialRecipes.recipes as unknown as ThemeSource[`recipes`],
  }
}

