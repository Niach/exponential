export function themeSchema(): Record<string, unknown> {
  const parts = recipeParts()
  const hexSchema = { $ref: `#/$defs/hex` }
  const numberMap = (names: readonly string[]) => ({ type: `object`, additionalProperties: false, properties: Object.fromEntries(names.map((n) => [n, { type: `number` }])) })
  const stringMap = (names: readonly string[]) => ({ type: `object`, additionalProperties: false, properties: Object.fromEntries(names.map((n) => [n, { type: `string`, minLength: 1 }])) })
  const colorOrToken = { anyOf: [hexSchema, { type: `string`, pattern: `^\\$color\\.[a-zA-Z0-9]+$` }] }
  const numOrToken = (groups: string[]) => ({ anyOf: [{ type: `number` }, { type: `string`, pattern: `^\\$(${groups.join(`|`).replace(/\./g, `\\.`)})\\.[a-zA-Z0-9]+$` }] })
  const styleProps: Record<string, unknown> = {
    backgroundColor: colorOrToken,
    color: colorOrToken,
    borderColor: colorOrToken,
    borderWidth: numOrToken([`border`, `control`]),
    borderTopWidth: numOrToken([`border`, `control`]),
    borderRightWidth: numOrToken([`border`, `control`]),
    borderBottomWidth: numOrToken([`border`, `control`]),
    borderLeftWidth: numOrToken([`border`, `control`]),
    borderRadius: numOrToken([`radius`, `spacing`]),
    borderStyle: { enum: styleKeyEnum(`borderStyle`) },
    padding: numOrToken([`spacing`]),
    paddingHorizontal: numOrToken([`spacing`]),
    paddingVertical: numOrToken([`spacing`]),
    gap: numOrToken([`spacing`]),
    width: numOrToken([`control`, `spacing`, `border`]),
    height: numOrToken([`control`, `spacing`, `border`]),
    minWidth: numOrToken([`control`, `spacing`]),
    minHeight: numOrToken([`control`, `spacing`]),
    fontSize: numOrToken([`type.size`]),
    fontWeight: { anyOf: [{ enum: styleKeyEnum(`fontWeight`) }, { type: `string`, pattern: `^\\$type\\.weight\\.[a-zA-Z0-9]+$` }] },
    lineHeight: numOrToken([`type.lineHeight`]),
    fontFamily: { type: `string`, pattern: `^\\$type\\.family\\.[a-zA-Z0-9]+$` },
    letterSpacing: { type: `number` },
    textDecoration: { enum: styleKeyEnum(`textDecoration`) },
    textTransform: { enum: styleKeyEnum(`textTransform`) },
    fontStyle: { enum: styleKeyEnum(`fontStyle`) },
    boxShadow: { type: `string`, pattern: `^\\$shadow\\.[a-zA-Z0-9]+$` },
    opacity: { anyOf: [{ type: `number`, minimum: 0, maximum: 1 }, { type: `string`, pattern: `^\\$opacity\\.[a-zA-Z0-9]+$` }] },
    transition: { type: `string`, pattern: `^\\$motion\\.[a-zA-Z0-9]+$` },
    transitionEasing: { type: `string`, pattern: `^\\$ease\\.[a-zA-Z0-9]+$` },
    transform: { type: `string`, pattern: STYLE_TRANSFORM_PATTERN },
    backdropBlur: { type: `string`, pattern: `^\\$blur\\.[a-zA-Z0-9]+$` },
    animation: { enum: styleKeyEnum(`animation`) },
    native: { type: `boolean` },
  }
  for (const key of RECIPE_KEYS) if (!styleProps[key]) throw new Error(`theme schema: no schema for recipe key ${key}`)
  const whenValue = { anyOf: [{ type: `string` }, { type: `number` }, { type: `boolean` }, { type: `array`, items: { anyOf: [{ type: `string` }, { type: `number` }, { type: `boolean` }] } }] }
  const rule = (props: string[]) => ({
    type: `object`,
    additionalProperties: false,
    required: [`style`],
    properties: {
      when: {
        type: `object`,
        additionalProperties: false,
        properties: {
          state: { anyOf: [{ enum: RECIPE_STATES }, { type: `array`, items: { enum: RECIPE_STATES } }] },
          ...Object.fromEntries(props.map((p) => [p, whenValue])),
        },
      },
      style: { $ref: `#/$defs/recipeStyle` },
    },
  })
  const recipes = {
    type: `object`,
    additionalProperties: false,
    properties: Object.fromEntries(
      Object.entries(parts).map(([component, spec]) => [
        component,
        { type: `object`, additionalProperties: false, properties: Object.fromEntries(spec.parts.map((part) => [part, { type: `array`, items: rule(spec.props) }])) },
      ])
    ),
  }
  const mode = {
    type: `object`,
    additionalProperties: false,
    properties: {
      color: { type: `object`, additionalProperties: false, properties: Object.fromEntries(TOKEN_GROUPS.color.map((n) => [n, hexSchema])) },
      shadow: { type: `object`, additionalProperties: false, properties: Object.fromEntries(TOKEN_GROUPS.shadow.map((n) => [n, { $ref: `#/$defs/shadow` }])) },
    },
  }
  return {
    $schema: `https://json-schema.org/draft/2020-12/schema`,
    $id: THEME_SCHEMA_ID,
    title: `Exponential UI theme`,
    description: `${THEME_HEADER} A theme = token VALUES per mode (colours, shadows) + the mode-less token groups + fonts + component recipes. With \`extends\`, every section is optional and overrides the parent's; a root theme must give every token a value (the loader checks completeness, which a schema cannot).`,
    type: `object`,
    additionalProperties: false,
    required: [`id`, `name`],
    properties: {
      $schema: { type: `string` },
      $comment: { type: `string` },
      id: { type: `string`, pattern: `^[a-z][a-z0-9-]*$` },
      name: { type: `string`, minLength: 1 },
      extends: { type: `string`, description: `The id of the theme this one overrides (a built-in or a loaded theme).` },
      modes: { type: `object`, additionalProperties: false, properties: { light: mode, dark: mode } },
      contrast: { type: `object`, additionalProperties: false, description: `High-contrast overlays per mode: colours/shadows a renderer merges over the mode when the platform (or the host) asks for more contrast.`, properties: { light: mode, dark: mode } },
      tokens: {
        type: `object`,
        additionalProperties: false,
        properties: {
          spacing: numberMap(TOKEN_GROUPS.spacing),
          radius: numberMap(TOKEN_GROUPS.radius),
          type: {
            type: `object`,
            additionalProperties: false,
            properties: {
              size: numberMap(TOKEN_GROUPS[`type.size`]),
              lineHeight: numberMap(TOKEN_GROUPS[`type.lineHeight`]),
              weight: numberMap(TOKEN_GROUPS[`type.weight`]),
              family: stringMap(TOKEN_GROUPS[`type.family`]),
            },
          },
          control: numberMap(TOKEN_GROUPS.control),
          opacity: numberMap(TOKEN_GROUPS.opacity),
          border: numberMap(TOKEN_GROUPS.border),
          motion: numberMap(TOKEN_GROUPS.motion),
          breakpoint: numberMap(TOKEN_GROUPS.breakpoint),
          ease: { type: `object`, additionalProperties: false, properties: Object.fromEntries(TOKEN_GROUPS.ease.map((n) => [n, { type: `array`, items: { type: `number` }, minItems: 4, maxItems: 4 }])) },
          density: numberMap(TOKEN_GROUPS.density),
          blur: numberMap(TOKEN_GROUPS.blur),
        },
      },
      fonts: {
        type: `object`,
        additionalProperties: {
          type: `object`,
          additionalProperties: false,
          properties: { fallback: { type: `string` }, weights: { type: `array`, items: { type: `number` } }, source: { enum: [`system`, `host`] } },
        },
      },
      recipes,
    },
    if: { not: { required: [`extends`] } },
    then: { required: [`modes`, `tokens`, `recipes`] },
    $defs: {
      hex: { type: `string`, pattern: `^#([0-9a-f]{6}|[0-9a-f]{8})$`, description: `#rrggbb or #rrggbbaa, lowercase.` },
      shadow: { type: `array`, items: { type: `object`, additionalProperties: false, required: [`x`, `y`, `blur`, `spread`, `color`], properties: { x: { type: `number` }, y: { type: `number` }, blur: { type: `number` }, spread: { type: `number` }, color: hexSchema } } },
      recipeStyle: { type: `object`, additionalProperties: false, properties: styleProps },
    },
  }
}

