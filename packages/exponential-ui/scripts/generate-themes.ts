interface RecipeTuple {
  component: string
  part: string
  props: Record<string, unknown>
}

function tupleKey(t: RecipeTuple): string {
  return `${t.component}/${t.part}/${JSON.stringify(t.props)}`
}

function walk(node: UiNode, visit: (n: UiNode) => void): void {
  visit(node)
  for (const slot of Object.values(node.slots ?? {})) walk(slot, visit)
  node.children.forEach((c) => walk(c, visit))
}

/** Every (component, part, props) a theme can be asked about: each native
 *  part × its props varied one at a time over the defaults, each macro part
 *  as the component cases + the kitchen sink produce it. */
export function recipeTuples(componentCases: { node: NestedNode }[], kitchen: NestedNode): RecipeTuple[] {
  const parts = recipeParts()
  const seen = new Map<string, RecipeTuple>()
  const add = (t: RecipeTuple) => {
    const key = tupleKey(t)
    if (!seen.has(key)) seen.set(key, t)
  }
  for (const [name, def] of Object.entries(coreCatalog.components)) {
    if (def.kind !== `native`) continue
    const spec = parts[name]
    const defaults = nativeRecipeProps(name, def.example ?? {})
    const combos: Record<string, unknown>[] = [defaults]
    for (const prop of spec.props) {
      const schema = def.props[prop]
      if (!schema) continue
      const values = schema.type === `boolean` ? [true, false] : (schema.values ?? coreCatalog.enums[schema.enum ?? ``] ?? [])
      for (const value of values) combos.push({ ...defaults, [prop]: value })
    }
    for (const part of spec.parts) for (const props of combos) add({ component: name, part, props })
  }
  const trees = [...componentCases.map((c) => reduceNested(c.node, { catalogId: CORE_CATALOG_ID }).root), reduceNested(kitchen, { catalogId: CORE_CATALOG_ID }).root]
  for (const tree of trees) walk(tree, (n) => { if (n.recipe) add({ component: n.recipe.macro, part: n.recipe.part, props: n.recipe.props }) })
  return [...seen.values()]
}

const same = (a: unknown, b: unknown) => JSON.stringify(a) === JSON.stringify(b)

export function recipesFixture(themes: ResolvedTheme[], tuples: RecipeTuple[]) {
  const cases = tuples
    .map((t) => {
      const visuals: Record<string, Record<string, Record<string, ResolvedStyle>>> = {}
      let any = false
      for (const theme of themes) {
        const byMode: Record<string, Record<string, ResolvedStyle>> = {}
        for (const mode of MODES) {
          const base = resolveRecipe(theme, { ...t, states: [] }, mode)
          const byState: Record<string, ResolvedStyle> = { default: base }
          for (const state of RECIPE_STATES) {
            const style = resolveRecipe(theme, { ...t, states: [state] }, mode)
            if (!same(style, base)) byState[state] = style
          }
          if (Object.keys(base).length > 0 || Object.keys(byState).length > 1) any = true
          byMode[mode] = byState
        }
        visuals[theme.id] = byMode
      }
      return any ? { ...t, visuals } : null
    })
    .filter((c): c is NonNullable<typeof c> => c !== null)
    // One case per distinct look: a prop value no theme keys on (Input
    // type=email…) resolves exactly like the defaults and is dropped.
    .filter((c, i, all) => all.findIndex((o) => o.component === c.component && o.part === c.part && same(o.visuals, c.visuals)) === i)
  return {
    $comment: `${THEME_HEADER} theme × component part × recipe props → the resolved visuals per mode (\`default\` = no state; a state appears only where it changes something; one case per distinct look per part). Every painter resolves the same: the native's own recipe < the node's style < the macro part's recipe (src/theme.ts resolveNodeStyle); this file locks the recipe half.`,
    themes: themes.map((t) => t.id),
    states: RECIPE_STATES,
    cases,
  }
}

export function extendsFixture(file: { $comment: string; cases: { name: string; theme: ThemeSource; probes: (RecipeQuery & { mode: ModeName })[] }[] }, sources: ThemeSource[]) {
  return {
    $comment: file.$comment,
    cases: file.cases.map((c) => {
      const theme = loadTheme(c.theme, { themes: sources })
      return {
        name: c.name,
        theme: c.theme,
        probes: c.probes,
        expected: {
          chain: theme.chain,
          probes: c.probes.map((p) => ({ ...p, style: resolveRecipe(theme, { component: p.component, part: p.part, props: p.props, states: p.states }, p.mode) })),
        },
      }
    }),
  }
}

export function invalidFixture(file: { $comment: string; cases: { name: string; theme: unknown }[] }, sources: ThemeSource[]) {
  return {
    $comment: file.$comment,
    cases: file.cases.map((c) => {
      const { theme, issues } = tryLoadTheme(c.theme, { themes: sources })
      if (theme) throw new Error(`theme-invalid.json: "${c.name}" loaded without issues`)
      return { name: c.name, theme: c.theme, issues }
    }),
  }
}

export function geometryFixture(themes: ResolvedTheme[]) {
  const parts = recipeParts()
  const out: Record<string, Record<string, Record<string, unknown>>> = {}
  for (const theme of themes) {
    const byComponent: Record<string, Record<string, unknown>> = {}
    for (const component of Object.keys(CONTROL_PARTS)) {
      const def = coreCatalog.components[component]
      const spec = parts[component]
      const defaults = nativeRecipeProps(component, def.example ?? {})
      const combos: { name: string; props: Record<string, unknown> }[] = [{ name: `default`, props: defaults }]
      for (const prop of spec.props) {
        const schema = def.props[prop]
        if (!schema || schema.type !== `enum`) continue
        for (const value of schema.values ?? coreCatalog.enums[schema.enum ?? ``] ?? []) combos.push({ name: `${prop}=${value}`, props: { ...defaults, [prop]: value } })
      }
      const cases: Record<string, unknown> = {}
      for (const c of combos) cases[c.name] = { props: c.props, geometry: controlGeometry(theme, component, c.props) }
      byComponent[component] = { part: CONTROL_PARTS[component], cases }
    }
    out[theme.id] = byComponent
  }
  return {
    $comment: `${THEME_HEADER} The measure contract: per built-in theme and control, the box the recipe of its sizing part fixes (px). A painter — built in or a host's override (VAPP-91) — must produce exactly this box; src/geometry.ts checkGeometry is the check the conformance suite runs.`,
    parts: CONTROL_PARTS,
    themes: out,
  }
}

export function themesDocs(themes: ResolvedTheme[]) {
  const parts = recipeParts()
  return {
    $comment: `${THEME_HEADER} What ui.exponential.at renders as the theme pages (VAPP-93): the token vocabulary with every built-in's values, the recipe contract per component, the built-ins.`,
    schemaId: THEME_SCHEMA_ID,
    themes: themes.map((t) => ({ id: t.id, name: t.name, chain: t.chain, fonts: t.fonts })),
    tokens: Object.fromEntries(
      Object.entries(TOKEN_GROUPS).map(([group, names]) => [
        group,
        names.map((name) => ({
          name,
          ref: `$${group}.${name}`,
          values: Object.fromEntries(
            themes.map((t) => [
              t.id,
              group === `color` || group === `shadow`
                ? { light: t.modes.light[group as `color` | `shadow`][name], dark: t.modes.dark[group as `color` | `shadow`][name] }
                : group.startsWith(`type.`)
                  ? (t.tokens.type as unknown as Record<string, Record<string, unknown>>)[group.slice(5)][name]
                  : (t.tokens as unknown as Record<string, Record<string, unknown>>)[group][name],
            ])
          ),
        })),
      ])
    ),
    states: RECIPE_STATES,
    keys: RECIPE_KEYS,
    components: Object.entries(parts).map(([name, spec]) => ({ name, kind: coreCatalog.components[name]?.kind, parts: spec.parts, props: spec.props })),
  }
}

function readJson<T>(rel: string): T {
  return JSON.parse(readFileSync(join(pkgRoot, rel), `utf8`)) as T
}

/** Every theme output, keyed by path relative to the package root. */
export function renderThemes(componentCases: { node: NestedNode }[], kitchen: NestedNode): Record<string, string> {
  const sources = builtinSources()
  const themes = sources.map((s) => loadTheme(s, { themes: sources }))
  const exponential = sources[1]
  return {
    "themes/exponential.theme.json": json({ $comment: `${THEME_HEADER} Composed by scripts/generate-themes.ts composeExponential(): edit themes/exponential.recipes.json, packages/design-tokens/tokens.json or packages/ui/src/styles.css and regenerate.`, ...exponential }),
    "catalog/theme.schema.json": json(themeSchema()),
    "generated/ExponentialUIThemes.generated.swift": renderThemesSwift(themes),
    "generated/ExponentialUIThemes.generated.kt": renderThemesKotlin(themes),
    "generated/catalog.themes.generated.rs": renderThemesRust(themes),
    "docs/themes.generated.json": json(themesDocs(themes)),
    "fixtures/theme-resolved.json": json({ $comment: `${THEME_HEADER} Every built-in theme RESOLVED (extends flattened, every token present, recipes merged): what a painter holds at startup and what a native loader must produce from the same source files.`, themes: Object.fromEntries(themes.map((t) => [t.id, t])) }),
    "fixtures/theme-recipes.json": json(recipesFixture(themes, recipeTuples(componentCases, kitchen))),
    "fixtures/theme-extends.json": json(extendsFixture(readJson(`fixtures/theme-extends.json`), sources)),
    "fixtures/theme-invalid.json": json(invalidFixture(readJson(`fixtures/theme-invalid.json`), sources)),
    "fixtures/control-geometry.json": json(geometryFixture(themes)),
  }
}
