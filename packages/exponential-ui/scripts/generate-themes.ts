function nativeRows(themes: ResolvedTheme[]) {
  const parts = recipeParts()
  return {
    ids: themes.map((t) => t.id),
    names: themes.map((t) => t.name),
    jsons: themes.map((t) => JSON.stringify(t)),
    components: Object.keys(parts),
    partLists: Object.values(parts).map((p) => p.parts.join(`,`)),
    propLists: Object.values(parts).map((p) => p.props.join(`,`)),
  }
}

