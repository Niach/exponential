// #EXP-1504: contract.json → eCore for Rust (apps/desktop/crates/ecore), TS
// (src/contract.generated.ts), Swift (ExpCore) and Kotlin
// (com.exponential.app.ecore). The enums, the constants and the pure rules
// are emitted from one template per language, so all four agree by
// construction; fixtures/ecore.json replays on each.
// Run with: `bun run --filter @exp/ecore generate`.

import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(__dirname, "..", "..", "..")

interface Contract {
  version: number
  id: { kinds: string[]; maxLength: number; extraChars: string }
  token: { scheme: string; length: number; alphabet: string }
  capability: { values: string[] }
  deliveryVerdict: { values: string[]; mayRetry: string[] }
  error: { codes: string[]; refusalCodes: string[]; retryableCodes: string[]; messageMax: number }
  envelope: { version: number; kindMax: number }
}

const c = JSON.parse(readFileSync(join(__dirname, "..", "contract.json"), "utf8")) as Contract

const words = (v: string) => v.split(/[_:.-]/).filter(Boolean)
const pascal = (v: string) => words(v).map((w) => w[0]!.toUpperCase() + w.slice(1)).join("")
const camel = (v: string) => {
  const p = pascal(v)
  return p[0]!.toLowerCase() + p.slice(1)
}
const upper = (v: string) => words(v).join("_").toUpperCase()

interface Enum {
  name: string
  doc: string
  values: string[]
}
const ENUMS: Enum[] = [
  { name: "IdKind", doc: "What an id points at.", values: c.id.kinds },
  { name: "Capability", doc: "What a grant lets a caller do on a device.", values: c.capability.values },
  { name: "DeliveryVerdict", doc: "How a tool call's side effect ended.", values: c.deliveryVerdict.values },
  { name: "ErrorCode", doc: "Why a call failed or was refused.", values: c.error.codes },
]

const HEADER = "GENERATED by packages/ecore/scripts/generate.ts from contract.json. Do not edit by hand."

// ── Rust ────────────────────────────────────────────────────────────────

const rustEnum = (e: Enum) => `/// ${e.doc}
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
pub enum ${e.name} {
${e.values.map((v) => `    #[serde(rename = "${v}")]\n    ${pascal(v)},`).join("\n")}
}

impl ${e.name} {
    pub const ALL: [${e.name}; ${e.values.length}] = [${e.values.map((v) => `Self::${pascal(v)}`).join(", ")}];

    /// The wire value.
    pub fn as_str(self) -> &'static str {
        match self {
${e.values.map((v) => `            Self::${pascal(v)} => "${v}",`).join("\n")}
        }
    }

    /// The variant for a wire value; \`None\` for an unknown one.
    pub fn parse(value: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|v| v.as_str() == value)
    }
}

impl std::fmt::Display for ${e.name} {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.as_str())
    }
}
`

const rust = `// ${HEADER}

use serde::{Deserialize, Serialize};

pub const CONTRACT_VERSION: u32 = ${c.version};
pub const ID_MAX_LENGTH: usize = ${c.id.maxLength};
pub const ID_EXTRA_CHARS: &str = "${c.id.extraChars}";
pub const TOKEN_SCHEME: &str = "${c.token.scheme}";
pub const TOKEN_LENGTH: usize = ${c.token.length};
pub const TOKEN_ALPHABET: &str = "${c.token.alphabet}";
pub const ERROR_MESSAGE_MAX: usize = ${c.error.messageMax};
pub const ENVELOPE_VERSION: u32 = ${c.envelope.version};
pub const ENVELOPE_KIND_MAX: usize = ${c.envelope.kindMax};

${ENUMS.map(rustEnum).join("\n")}
impl DeliveryVerdict {
    /// May the caller repeat the call?
    pub fn may_retry(self) -> bool {
        matches!(self, ${c.deliveryVerdict.mayRetry.map((v) => `Self::${pascal(v)}`).join(" | ")})
    }
}

impl ErrorCode {
    /// Did the callee choose to refuse (rather than fail)?
    pub fn is_refusal(self) -> bool {
        matches!(self, ${c.error.refusalCodes.map((v) => `Self::${pascal(v)}`).join(" | ")})
    }

    /// \`retryable\` when the callee does not say.
    pub fn default_retryable(self) -> bool {
        matches!(self, ${c.error.retryableCodes.map((v) => `Self::${pascal(v)}`).join(" | ")})
    }
}

/// 1..=ID_MAX_LENGTH ASCII letters, digits and ID_EXTRA_CHARS, starting
/// with a letter or digit.
pub fn is_valid_id(id: &str) -> bool {
    let mut chars = id.chars();
    match chars.next() {
        Some(first) if first.is_ascii_alphanumeric() => {}
        _ => return false,
    }
    id.len() <= ID_MAX_LENGTH && chars.all(|ch| ch.is_ascii_alphanumeric() || ID_EXTRA_CHARS.contains(ch))
}

/// Exactly TOKEN_LENGTH characters of TOKEN_ALPHABET.
pub fn is_valid_token(token: &str) -> bool {
    token.len() == TOKEN_LENGTH && token.chars().all(|ch| TOKEN_ALPHABET.contains(ch))
}

/// The \`Authorization\` header value for a token.
pub fn bearer_header(token: &str) -> String {
    format!("{TOKEN_SCHEME} {token}")
}

/// The token in an \`Authorization\` header: \`<scheme> <token>\` (one space,
/// the scheme case-insensitive, outer whitespace ignored).
pub fn parse_bearer(header: &str) -> Option<&str> {
    let (scheme, token) = header.trim().split_once(' ')?;
    (scheme.eq_ignore_ascii_case(TOKEN_SCHEME) && is_valid_token(token)).then_some(token)
}

/// Does a grant with \`capabilities\` and \`expires_at\` (unix ms) admit
/// \`capability\` at \`now\`?
pub fn grant_admits(capabilities: &[Capability], expires_at: Option<i64>, now: i64, capability: Capability) -> bool {
    capabilities.contains(&capability) && expires_at.is_none_or(|at| now < at)
}

/// The first ERROR_MESSAGE_MAX characters of a message.
pub fn clamp_message(message: &str) -> String {
    message.chars().take(ERROR_MESSAGE_MAX).collect()
}

/// Dotted lowercase segments (\`session.turn_ended\`), 1..=ENVELOPE_KIND_MAX.
pub fn is_valid_event_kind(kind: &str) -> bool {
    !kind.is_empty()
        && kind.len() <= ENVELOPE_KIND_MAX
        && kind.split('.').all(|segment| {
            let mut chars = segment.chars();
            matches!(chars.next(), Some(first) if first.is_ascii_lowercase())
                && chars.all(|ch| ch.is_ascii_lowercase() || ch.is_ascii_digit() || ch == '_')
        })
}

/// Every envelope field that breaks a rule, in the contract's order.
pub fn envelope_errors(v: i64, id: &str, kind: &str, at: i64, source: &str, session_id: Option<&str>) -> Vec<&'static str> {
    let mut errors = Vec::new();
    if v != ENVELOPE_VERSION as i64 {
        errors.push("v");
    }
    if !is_valid_id(id) {
        errors.push("id");
    }
    if !is_valid_event_kind(kind) {
        errors.push("kind");
    }
    if at < 0 {
        errors.push("at");
    }
    if !is_valid_id(source) {
        errors.push("source");
    }
    if session_id.is_some_and(|id| !is_valid_id(id)) {
        errors.push("sessionId");
    }
    errors
}
`

