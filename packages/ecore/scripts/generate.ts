const ts = `// ${HEADER}

export const CONTRACT_VERSION = ${c.version}
export const ID_MAX_LENGTH = ${c.id.maxLength}
export const ID_EXTRA_CHARS = "${c.id.extraChars}"
export const TOKEN_SCHEME = "${c.token.scheme}"
export const TOKEN_LENGTH = ${c.token.length}
export const TOKEN_ALPHABET = "${c.token.alphabet}"
export const ERROR_MESSAGE_MAX = ${c.error.messageMax}
export const ENVELOPE_VERSION = ${c.envelope.version}
export const ENVELOPE_KIND_MAX = ${c.envelope.kindMax}

${ENUMS.map(tsEnum).join("\n")}
const MAY_RETRY: readonly DeliveryVerdict[] = [${c.deliveryVerdict.mayRetry.map((v) => `"${v}"`).join(", ")}]
const REFUSAL_CODES: readonly ErrorCode[] = [${c.error.refusalCodes.map((v) => `"${v}"`).join(", ")}]
const RETRYABLE_CODES: readonly ErrorCode[] = [${c.error.retryableCodes.map((v) => `"${v}"`).join(", ")}]

/** May the caller repeat the call? */
export const mayRetry = (verdict: DeliveryVerdict): boolean => MAY_RETRY.includes(verdict)
/** Did the callee choose to refuse (rather than fail)? */
export const isRefusal = (code: ErrorCode): boolean => REFUSAL_CODES.includes(code)
/** \`retryable\` when the callee does not say. */
export const defaultRetryable = (code: ErrorCode): boolean => RETRYABLE_CODES.includes(code)

const isAsciiAlnum = (ch: string) => /^[A-Za-z0-9]$/.test(ch)

/** 1..ID_MAX_LENGTH ASCII letters, digits and ID_EXTRA_CHARS, starting with a letter or digit. */
export const isValidId = (id: string): boolean => {
  if (id.length === 0 || id.length > ID_MAX_LENGTH || !isAsciiAlnum(id[0]!)) return false
  for (const ch of id) if (!isAsciiAlnum(ch) && !ID_EXTRA_CHARS.includes(ch)) return false
  return true
}

/** Exactly TOKEN_LENGTH characters of TOKEN_ALPHABET. */
export const isValidToken = (token: string): boolean =>
  token.length === TOKEN_LENGTH && [...token].every((ch) => TOKEN_ALPHABET.includes(ch))

/** The \`Authorization\` header value for a token. */
export const bearerHeader = (token: string): string => \`\${TOKEN_SCHEME} \${token}\`

/** The token in an \`Authorization\` header: \`<scheme> <token>\` (one space, the scheme case-insensitive, outer whitespace ignored). */
export const parseBearer = (header: string): string | null => {
  const trimmed = header.trim()
  const space = trimmed.indexOf(" ")
  if (space < 0) return null
  const scheme = trimmed.slice(0, space)
  const token = trimmed.slice(space + 1)
  return scheme.toLowerCase() === TOKEN_SCHEME.toLowerCase() && isValidToken(token) ? token : null
}

/** Does a grant with \`capabilities\` and \`expiresAt\` (unix ms) admit \`capability\` at \`now\`? */
export const grantAdmits = (
  capabilities: readonly Capability[],
  expiresAt: number | null,
  now: number,
  capability: Capability
): boolean => capabilities.includes(capability) && (expiresAt === null || now < expiresAt)

/** The first ERROR_MESSAGE_MAX characters (Unicode scalars) of a message. */
export const clampMessage = (message: string): string => Array.from(message).slice(0, ERROR_MESSAGE_MAX).join("")

/** Dotted lowercase segments (\`session.turn_ended\`), 1..ENVELOPE_KIND_MAX. */
export const isValidEventKind = (kind: string): boolean =>
  kind.length > 0 && kind.length <= ENVELOPE_KIND_MAX && kind.split(".").every((s) => /^[a-z][a-z0-9_]*$/.test(s))

/** Every envelope field that breaks a rule, in the contract's order. */
export const envelopeErrors = (e: {
  v: number
  id: string
  kind: string
  at: number
  source: string
  sessionId?: string | null
}): string[] => {
  const errors: string[] = []
  if (e.v !== ENVELOPE_VERSION) errors.push("v")
  if (!isValidId(e.id)) errors.push("id")
  if (!isValidEventKind(e.kind)) errors.push("kind")
  if (!Number.isInteger(e.at) || e.at < 0) errors.push("at")
  if (!isValidId(e.source)) errors.push("source")
  if (e.sessionId != null && !isValidId(e.sessionId)) errors.push("sessionId")
  return errors
}
`

// ── Swift ───────────────────────────────────────────────────────────────

// Swift declaration keywords need backticks as case names (\`internal\`).
const SWIFT_RESERVED = new Set(["internal", "public", "private", "default", "case", "class", "struct", "enum", "protocol", "extension", "func", "import", "init", "let", "var", "static", "self", "super", "true", "false", "nil", "in", "is", "as", "do", "if", "else", "for", "while", "return", "throw", "try", "switch", "where", "repeat", "break", "continue", "operator", "subscript", "typealias", "associatedtype", "deinit", "fileprivate", "open", "inout", "guard", "defer", "catch", "throws", "rethrows", "Any", "Type"])
const swiftCase = (v: string) => (SWIFT_RESERVED.has(camel(v)) ? `\`${camel(v)}\`` : camel(v))

const swiftEnum = (e: Enum) => `    /// ${e.doc}
    public enum ${e.name}: String, CaseIterable, Codable, Sendable {
${e.values.map((v) => `        case ${swiftCase(v)} = "${v}"`).join("\n")}
    }
`

const swift = `// ${HEADER}

import Foundation

/// eCore (#EXP-1504): the plain types every module shares.
public enum ECore {
    public static let contractVersion = ${c.version}
    public static let idMaxLength = ${c.id.maxLength}
    public static let idExtraChars = "${c.id.extraChars}"
    public static let tokenScheme = "${c.token.scheme}"
    public static let tokenLength = ${c.token.length}
    public static let tokenAlphabet = "${c.token.alphabet}"
    public static let errorMessageMax = ${c.error.messageMax}
    public static let envelopeVersion = ${c.envelope.version}
    public static let envelopeKindMax = ${c.envelope.kindMax}

${ENUMS.map(swiftEnum).join("\n")}
    /// May the caller repeat the call?
    public static func mayRetry(_ verdict: DeliveryVerdict) -> Bool {
        ([${c.deliveryVerdict.mayRetry.map((v) => `.${camel(v)}`).join(", ")}] as [DeliveryVerdict]).contains(verdict)
    }

    /// Did the callee choose to refuse (rather than fail)?
    public static func isRefusal(_ code: ErrorCode) -> Bool {
        ([${c.error.refusalCodes.map((v) => `.${camel(v)}`).join(", ")}] as [ErrorCode]).contains(code)
    }

    /// \`retryable\` when the callee does not say.
    public static func defaultRetryable(_ code: ErrorCode) -> Bool {
        ([${c.error.retryableCodes.map((v) => `.${camel(v)}`).join(", ")}] as [ErrorCode]).contains(code)
    }

    private static func isAsciiAlnum(_ ch: Unicode.Scalar) -> Bool {
        ch.isASCII && (("a"..."z").contains(ch) || ("A"..."Z").contains(ch) || ("0"..."9").contains(ch))
    }

    /// 1...idMaxLength ASCII letters, digits and idExtraChars, starting with a letter or digit.
    public static func isValidId(_ id: String) -> Bool {
        let scalars = Array(id.unicodeScalars)
        guard let first = scalars.first, isAsciiAlnum(first), scalars.count <= idMaxLength else { return false }
        return scalars.allSatisfy { isAsciiAlnum($0) || idExtraChars.unicodeScalars.contains($0) }
    }

    /// Exactly tokenLength characters of tokenAlphabet.
    public static func isValidToken(_ token: String) -> Bool {
        token.unicodeScalars.count == tokenLength && token.unicodeScalars.allSatisfy { tokenAlphabet.unicodeScalars.contains($0) }
    }

    /// The \`Authorization\` header value for a token.
    public static func bearerHeader(_ token: String) -> String { "\\(tokenScheme) \\(token)" }

    /// The token in an \`Authorization\` header: \`<scheme> <token>\` (one space, the scheme case-insensitive, outer whitespace ignored).
    public static func parseBearer(_ header: String) -> String? {
        let trimmed = header.trimmingCharacters(in: .whitespacesAndNewlines)
        guard let space = trimmed.firstIndex(of: " ") else { return nil }
        let scheme = trimmed[..<space]
        let token = String(trimmed[trimmed.index(after: space)...])
        return scheme.lowercased() == tokenScheme.lowercased() && isValidToken(token) ? token : nil
    }

    /// Does a grant with \`capabilities\` and \`expiresAt\` (unix ms) admit \`capability\` at \`now\`?
    public static func grantAdmits(capabilities: [Capability], expiresAt: Int64?, now: Int64, capability: Capability) -> Bool {
        capabilities.contains(capability) && (expiresAt.map { now < $0 } ?? true)
    }

    /// The first errorMessageMax characters (Unicode scalars) of a message.
    public static func clampMessage(_ message: String) -> String {
        var out = String.UnicodeScalarView()
        out.append(contentsOf: message.unicodeScalars.prefix(errorMessageMax))
        return String(out)
    }

    /// Dotted lowercase segments (\`session.turn_ended\`), 1...envelopeKindMax.
    public static func isValidEventKind(_ kind: String) -> Bool {
        guard !kind.isEmpty, kind.unicodeScalars.count <= envelopeKindMax else { return false }
        return kind.split(separator: ".", omittingEmptySubsequences: false).allSatisfy { segment in
            let scalars = Array(segment.unicodeScalars)
            guard let first = scalars.first, ("a"..."z").contains(first) else { return false }
            return scalars.allSatisfy { ("a"..."z").contains($0) || ("0"..."9").contains($0) || $0 == "_" }
        }
    }

    /// Every envelope field that breaks a rule, in the contract's order.
    public static func envelopeErrors(v: Int, id: String, kind: String, at: Int64, source: String, sessionId: String?) -> [String] {
        var errors: [String] = []
        if v != envelopeVersion { errors.append("v") }
        if !isValidId(id) { errors.append("id") }
        if !isValidEventKind(kind) { errors.append("kind") }
        if at < 0 { errors.append("at") }
        if !isValidId(source) { errors.append("source") }
        if let sessionId, !isValidId(sessionId) { errors.append("sessionId") }
        return errors
    }
}
`

